/// Position of icon relative to label in ArxaKitCheckbox and ArxaKitRadio widgets
enum ArxaKitIconPosition {
  /// Icon above label (vertical layout)
  top,

  /// Icon to the left of label (horizontal layout) - DEFAULT
  left,

  /// Icon to the right of label (horizontal layout)
  right,

  /// Icon below label (vertical layout)
  bottom,
}
