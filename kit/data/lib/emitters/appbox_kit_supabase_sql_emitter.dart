/// Generates a Postgres/Supabase migration from [AppBoxKitTableSchema]
/// descriptors. Pure Dart — no `flutter` imports — so it runs under
/// `dart run` outside the Flutter toolchain (see `example/generate.dart`).
library;

import '../schema/appbox_kit_schema_topology.dart';
import '../schema/appbox_kit_table_schema.dart';

/// Emits one `create table if not exists` migration per schema, ordered so
/// that a table referenced by another table's `reference` column is created
/// first ([appBoxKitTopologicalSchemaOrder]).
class AppBoxKitSupabaseSqlEmitter {
  /// Renders [schemas] into a single migration SQL string.
  ///
  /// Throws [ArgumentError] if two or more distinct tables in [schemas]
  /// reference each other in a cycle — plain `create table` statements
  /// cannot satisfy that ordering (a self-referencing table is fine and is
  /// not treated as a cycle).
  String emit(List<AppBoxKitTableSchema> schemas) {
    final ordered = appBoxKitTopologicalSchemaOrder(schemas);

    final buffer = StringBuffer()
      ..writeln(
        '-- Generated by appbox_kit_data (AppBoxKitSupabaseSqlEmitter). Do not edit by hand.',
      )
      ..writeln(
        "-- note: Row Level Security policies and grants are the operator's responsibility; none are emitted here.",
      )
      ..writeln();

    for (final schema in ordered) {
      buffer.writeln('create table if not exists "${schema.table}" (');
      buffer.writeln(
        schema.columns.map(_columnLine).join(',\n'),
      );
      buffer.writeln(');');
      buffer.writeln();
    }

    return buffer.toString();
  }

  String _columnLine(AppBoxKitColumn column) {
    final buffer = StringBuffer('  "${column.name}" ')..write(
        _columnType(column),
      );
    if (!column.nullable) {
      buffer.write(' not null');
    }
    return buffer.toString();
  }

  String _columnType(AppBoxKitColumn column) {
    switch (column.type) {
      case AppBoxKitColumnType.id:
        return 'uuid primary key';
      case AppBoxKitColumnType.text:
        return 'text';
      case AppBoxKitColumnType.integer:
        return 'bigint';
      case AppBoxKitColumnType.real:
        return 'double precision';
      case AppBoxKitColumnType.boolean:
        return 'boolean';
      case AppBoxKitColumnType.timestamptz:
        return 'timestamptz';
      case AppBoxKitColumnType.jsonb:
        return 'jsonb';
      case AppBoxKitColumnType.reference:
        return 'uuid references "${column.references}"("id")';
    }
  }
}
