}

// ── the serve-time application ───────────────────────────────────────────

final _paletteAttrPattern = RegExp(r'\s+data-palette="[^"]*"');
final _htmlTagPattern = RegExp(r'<html\b[^>]*>');

class ServedPalette {
  const ServedPalette({
    required this.html,
    required this.active,
    required this.published,
    required this.palettesConfig,
  });

  /// The page with data-palette set on the <html> tag.
  final String html;

  /// What this page renders (?palette= override > published > default).
  final String active;

  /// What the store publishes (or the manifest default).
  final String published;

  /// The island's palettes array (manifest entries).
  final List<Map<String, Object?>> palettesConfig;
}

/// Resolve and apply the palette for one served page. Precedence mirrors
/// the axes law: a VALID ?palette= override beats the stored pick beats
/// the manifest default; unknown values fall through silently.
ServedPalette applyPaletteToServedHtml(
  String html, {
  required Map<String, String> query,
  required String? stored,
  required PaletteManifest manifest,
}) {
  String resolve(String? overrideValue, String? storedValue) {
    if (overrideValue != null && manifest.declares(overrideValue)) {
      return overrideValue;
    }
    if (storedValue != null && manifest.declares(storedValue)) {
      return storedValue;
    }
    return manifest.defaultId;
  }

  final published = resolve(null, stored);
  final active = resolve(query['palette'], stored);

  var out = html;
  final htmlMatch = _htmlTagPattern.firstMatch(out);
  if (htmlMatch != null) {
    final tag = htmlMatch.group(0)!;
    final stripped = tag.replaceAll(_paletteAttrPattern, '');
    final selfClosed = stripped.endsWith('/>');
    final core =
        stripped.substring(0, stripped.length - (selfClosed ? 2 : 1));
    final next = '$core data-palette="$active"${selfClosed ? '/>' : '>'}';
    if (next != tag) out = out.replaceFirst(tag, next);
  }

  // Wire every declared override sheet (ADDENDUM 18): the artifact's base
  // frame statically links the seeded sheets only — a pasted palette's
  // sheet existed on disk but was never <link>ed, so its tokens.css block
  // flipped while the 57 override rules stayed base (the "mixed palette
  // but nothing changes" report). Dedup by href keeps statically linked
  // sheets single; injected last so the cascade matches the static links.
  final links = StringBuffer();
  for (final e in manifest.palettes) {
    final sheet = e.sheet;
    if (sheet == null || sheet.isEmpty) continue;
    if (out.contains('href="$sheet"')) continue;
    links.write(
        '<link rel="stylesheet" href="$sheet" data-palette-sheet="${e.id}">');
  }
  if (links.isNotEmpty) {
    out = out.replaceFirst('</head>', '$links</head>');
  }

  // theme-color follows the ACTIVE palette at serve time (palette.js
  // keeps it current on live switches — this kills the wrong-chrome
  // flash before first paint).
  for (final e in manifest.palettes) {
    if (e.id != active) continue;
    out = out.replaceFirstMapped(
        RegExp(r'(<meta[^>]*name="theme-color"[^>]*content=")[^"]*(")'),
        (m) => '${m[1]}${e.themeColor}${m[2]}');
    break;
  }

  return ServedPalette(
    html: out,
    active: active,
    published: published,
    palettesConfig: [for (final e in manifest.palettes) e.toJson()],
  );
}

// ── Coolors ingestion ────────────────────────────────────────────────────

final _coolorsPattern = RegExp(
    r'(?:coolors\.co)?/?(?:palette/)?([0-9a-fA-F]{6}(?:-[0-9a-fA-F]{6}){4})');

/// Parse a Coolors link (or bare slug) into its 5 hexes, lowercased.
/// There is no official Coolors API (every /api/* candidate 404s; the
/// pages are CSR) — the URL slug IS the palette.
List<String>? parseCoolorsSlug(String input) {
  final match = _coolorsPattern.firstMatch(input.trim());
  if (match == null) return null;
  final slug = match.group(1)!;
  if (slug.split('-').length != 5) return null;
  return [for (final h in slug.split('-')) h.toLowerCase()];
}

/// The lightness-rank role law: sorted by HSL lightness, the five hexes
/// map darkest->dark, 2nd->accent, 3rd->field, 4th->beige (cards),
/// lightest->paper. Verified against Marine Blue and Green Oasis.
Map<String, String> anchorsFor(List<String> hexes) {
  double lightness(String h) {
    final rgb = hexToRgb(h);
    return rgbToHsl(rgb[0], rgb[1], rgb[2])[2];
  }
  final sorted = [...hexes]..sort((a, b) => lightness(a).compareTo(lightness(b)));
  return {
    'dark': sorted[0],
    'accent': sorted[1],
    'field': sorted[2],
    'beige': sorted[3],
    'paper': sorted[4],
  };
}

/// The pre-indexed color slots (generated by genpalettes.mjs — the design
/// ships it at assets/styles/palettes/_template.json).
/// A family-level pair (the general contract): every solid TEXT rule of
/// [fg] family must pass [level] against every surface RULE and every
/// mapped surface TOKEN of the [on] families. Expanded at solve time —
/// the artifact's real co-locations, erring readable.
class FamilyPair {
  const FamilyPair({required this.fg, required this.on, required this.level});
  final String fg;
  final List<String> on;
  final String level;
}

class PaletteTemplate {
  PaletteTemplate(
      {required this.anchors,
      required this.tokens,
      required this.rules,
      this.pairs = const [],
      this.familyPairs = const [],
      this.surfaces = const {},
      this.declaresContract = false});

  /// Base palette family anchors: family -> base hex.
  final Map<String, String> anchors;
  final List<Map<String, Object?>> tokens;
  final List<Map<String, Object?>> rules;

  /// The contrast contract (grilled 2026-09-11): explicit token/rule
  /// pairs, the family-level general pairs, and the family -> surface
  /// token map. [declaresContract] distinguishes a MODERN template
  /// (the keys are present, even if vacuously empty) from a legacy one
  /// (no keys at all): the solver no-ops on empty, and only a legacy
  /// template earns the gate's author-the-contract advisory.
  final List<ContrastPair> pairs;
  final List<FamilyPair> familyPairs;
  final Map<String, String> surfaces;
  final bool declaresContract;

  static PaletteTemplate? load(String artifactDir) {
    try {
      final f = File(p.join(
          artifactDir, 'assets', 'styles', 'palettes', '_template.json'));
      if (!f.existsSync()) return null;
      final parsed = jsonDecode(f.readAsStringSync());
      if (parsed is! Map) return null;
      final anchors = <String, String>{};
      (parsed['anchors'] as Map).forEach((k, v) => anchors['$k'] = '$v');
      final surfaces = <String, String>{};
      final rawSurfaces = parsed['surfaces'];
      if (rawSurfaces is Map) {
        rawSurfaces.forEach((k, v) => surfaces['$k'] = '$v');
      }
      final rawFamily = parsed['familyPairs'];
      final familyPairs = <FamilyPair>[];
      if (rawFamily is List) {
        for (final fp in rawFamily) {
          if (fp is! Map) continue;
          final fg = fp['fg'], on = fp['on'], level = fp['level'];
          if (fg is! String || on is! List || level is! String) continue;
          familyPairs.add(FamilyPair(
              fg: fg,
              on: [for (final f in on) '$f'],
              level: level));
        }
      }
      return PaletteTemplate(
        anchors: anchors,
        tokens: [
          for (final t in parsed['tokens'] as List)
            Map<String, Object?>.from(t as Map)
        ],
        rules: [
          for (final r in parsed['rules'] as List)
            Map<String, Object?>.from(r as Map)
        ],
        pairs: contractFromTemplate(parsed),
        familyPairs: familyPairs,
        surfaces: surfaces,
        declaresContract: parsed.containsKey('pairs') ||
            parsed.containsKey('familyPairs') ||
            parsed.containsKey('surfaces'),
      );
    } catch (_) {
      return null;
    }
  }
}

