/// The palette plane (VERIFY ADDENDUM 17, grilled 2026-09-09): color
/// palettes are dial-switchable on any artifact kind that DECLARES them in
/// <artifactDir>/palettes.json — the axes plane's kind gate opens for
/// sites here, while style/theme axes stay kind:app only.
///
/// The artifact owns the application plane: base stylesheets are the
/// default palette, generated override sheets under
/// assets/styles/palettes/ repaint every color-bearing rule under
/// html[data-palette="<id>"], tokens.css carries the per-palette var
/// blocks, and assets/app/palette.js owns the attribute + broadcast live.
/// THIS file owns the server side: the manifest, the serve-time attribute
/// (override > published > default), the Coolors ingestion that derives a
/// pasted palette and generates its sheet, and deletion.
///
/// Derivation law (transplant — the ONE home of the color math; the
/// template indexer, design_palette_index.dart, consumes it): a pasted
/// Coolors link yields 5 hexes; the lightness rank assigns roles
/// (darkest=dark, 2nd=accent, 3rd=field, 4th=beige/cards, lightest=paper);
/// every base color slot is re-rendered relative to its family anchor —
/// dh additive, saturation RATIO capped [0.3, 1.3] (uncapped, saturated
/// paper anchors turn the ramp gold), dL additive. The slots are
/// pre-indexed in assets/styles/palettes/_template.json (regenerated by
/// `arxa design palette-index`) so no CSS parsing happens here.
