/// The deletion strip: remove one entry's appended var block (comment +
/// [data-palette="<id>"] { ... }) from tokens.css text.
String stripTokensBlock(String text, String id) {
  return text.replaceAll(
      RegExp(
          '\\n*/\\* pasted palette $id[^\\n]*\\*/\\n\\[data-palette="$id"\\] \\{[^}]*\\}\\n?'),
