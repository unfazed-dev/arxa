// ── color math (1:1 with genpalettes.mjs) ───────────────────────────────

List<int> hexToRgb(String hex) {
  final h = hex.replaceFirst('#', '');
  return [
    int.parse(h.substring(0, 2), radix: 16),
    int.parse(h.substring(2, 4), radix: 16),
    int.parse(h.substring(4, 6), radix: 16),
  ];
}

String rgbToHex(num r, num g, num b) {
  int c(num v) => v.round().clamp(0, 255);
  return '#${c(r).toRadixString(16).padLeft(2, '0')}'
      '${c(g).toRadixString(16).padLeft(2, '0')}'
      '${c(b).toRadixString(16).padLeft(2, '0')}';
}

/// [h 0..360, s 0..100, l 0..100]
List<double> rgbToHsl(num r, num g, num b) {
  final rn = r / 255, gn = g / 255, bn = b / 255;
  final mx = math.max(rn, math.max(gn, bn));
  final mn = math.min(rn, math.min(gn, bn));
  final l = (mx + mn) / 2;
  var h = 0.0, s = 0.0;
  if (mx != mn) {
    final d = mx - mn;
    s = l > 0.5 ? d / (2 - mx - mn) : d / (mx + mn);
    if (mx == rn) {
      h = (gn - bn) / d + (gn < bn ? 6 : 0);
    } else if (mx == gn) {
      h = (bn - rn) / d + 2;
    } else {
      h = (rn - gn) / d + 4;
    }
    h *= 60;
  }
  return [h, s * 100, l * 100];
}

List<int> hslToRgb(num h, num s, num l) {
  final hn = ((h % 360) + 360) % 360;
  final sn = (s.clamp(0, 100)) / 100, ln = (l.clamp(0, 100)) / 100;
  final c = (1 - (2 * ln - 1).abs()) * sn;
  final x = c * (1 - (((hn / 60) % 2) - 1).abs());
  final m = ln - c / 2;
  var r = 0.0, g = 0.0, b = 0.0;
  if (hn < 60) {
    r = c; g = x;
  } else if (hn < 120) {
    r = x; g = c;
  } else if (hn < 180) {
    g = c; b = x;
  } else if (hn < 240) {
    g = x; b = c;
  } else if (hn < 300) {
    r = x; b = c;
  } else {
    r = c; b = x;
  }
  return [((r + m) * 255).round(), ((g + m) * 255).round(), ((b + m) * 255).round()];
}

/// The transplant: [base] rendered relative to its family anchor
/// [baseAnchor], replayed on the palette's anchor [paletteAnchor].
String transplant(String base, String baseAnchor, String paletteAnchor) {
  final bm = hexToRgb(base), ba = hexToRgb(baseAnchor), ga = hexToRgb(paletteAnchor);
  final hm = rgbToHsl(bm[0], bm[1], bm[2]);
  final ha = rgbToHsl(ba[0], ba[1], ba[2]);
  final hg = rgbToHsl(ga[0], ga[1], ga[2]);
  final dh = hm[0] - ha[0];
  var sr = ha[1] == 0 ? 1.0 : hm[1] / ha[1];
  sr = sr.clamp(0.3, 1.3);
  final dl = hm[2] - ha[2];
  final out = hslToRgb(hg[0] + dh, hg[1] * sr, hg[2] + dl);
  return rgbToHex(out[0], out[1], out[2]);
}

// ── the manifest ─────────────────────────────────────────────────────────

class PaletteEntry {
  const PaletteEntry({
    required this.id,
    required this.name,
    required this.swatch,
    required this.themeColor,
    this.seeded = false,
    this.source,
    this.sheet,
    this.auto = true,
  });

  /// The contrast law (grilled 2026-09-11): AUTO palettes render through
  /// the solver — their contracted pairs pass WCAG 2.2 AA by construction.
  /// A hand edit flips it to MANUAL: the author's hexes ship verbatim, the
  /// editor keeps showing the red pairs, the gate keeps failing them.
  final bool auto;

  final String id;
  final String name;
  final List<String> swatch; // 3..7 hexes (the variable-width law, Q5)
  final String themeColor;
  final bool seeded;
  final String? source;
  final String? sheet;

  Map<String, Object?> toJson() => {
        'id': id,
        'name': name,
        'swatch': swatch,
        'themeColor': themeColor,
        if (seeded) 'seeded': true,
        if (source != null) 'source': source,
        if (sheet != null) 'sheet': sheet,
        if (!auto) 'auto': false,
      };

  static PaletteEntry? fromJson(Object? json) {
    if (json is! Map) return null;
    final id = json['id'], name = json['name'], themeColor = json['themeColor'];
    final swatch = json['swatch'];
    if (id is! String || !axisValuePattern.hasMatch(id)) return null;
    if (name is! String || themeColor is! String) return null;
    if (swatch is! List || swatch.length < 3 || swatch.length > 7) {
      return null;
    }
    return PaletteEntry(
      id: id,
      name: name,
      swatch: [for (final s in swatch) s.toString()],
      themeColor: themeColor,
      seeded: json['seeded'] == true,
      source: json['source'] as String?,
      sheet: json['sheet'] as String?,
      auto: json['auto'] != false,
    );
  }
}

class PaletteManifest {
  PaletteManifest({required this.defaultId, required this.palettes});

  final String defaultId;
  final List<PaletteEntry> palettes;

  List<String> get ids => [for (final e in palettes) e.id];

  bool declares(String id) => palettes.any((e) => e.id == id);

  /// Null when the artifact declares no palette plane (or the manifest is
  /// malformed — a broken declaration disables the axis, never guesses).
  static PaletteManifest? load(String artifactDir) {
    try {
      final f = File(p.join(artifactDir, 'palettes.json'));
      if (!f.existsSync()) return null;
      final parsed = jsonDecode(f.readAsStringSync());
      if (parsed is! Map) return null;
      final def = parsed['default'];
      final list = parsed['palettes'];
      if (def is! String || list is! List) return null;
      final entries = <PaletteEntry>[];
      for (final raw in list) {
        final e = PaletteEntry.fromJson(raw);
        if (e == null) return null;
        entries.add(e);
      }
      if (entries.isEmpty || !entries.any((e) => e.id == def)) return null;
      return PaletteManifest(defaultId: def, palettes: entries);
    } catch (_) {
      return null;
    }
  }

  void save(String artifactDir) {
    final f = File(p.join(artifactDir, 'palettes.json'));
    const encoder = JsonEncoder.withIndent('  ');
    f.writeAsStringSync(encoder.convert({
      'version': 1,
      'comment':
          'Palette plane declaration (VERIFY ADDENDUM 17). id = html[data-palette] value; sheet = generated override under /assets/styles/palettes/ (the default palette is the base corpus, no sheet); swatch = the declared hexes (3..7 — the variable-width law; N=5 is the Coolors order); themeColor = meta theme-color while the palette is active. Pasted Coolors palettes are appended here by the dial server with a generated sheet, persist, and ship on the next eject.',
      'default': defaultId,
      'palettes': [for (final e in palettes) e.toJson()],
    }));
  }
}

