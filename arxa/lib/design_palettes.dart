/// Ingestion + deletion. The manifest saves LAST, so a crash mid-ingest
/// leaves an orphan sheet file, never a manifest pointing at nothing.
class PaletteIngestion {
  PaletteIngestion({required this.artifactDir});

  final String artifactDir;

  String _derive(Map<String, Object?> slot, Map<String, String> anchors,
      PaletteTemplate template,
      [Map<String, String>? solved, String? key]) {
    // The contrast engine's answer first: a solved slot ships the solved
    // hex (hex form) or the solved rgb (triplet forms) — same shape, new
    // lightness. Unsolved/absent falls through to the transplant.
    final solvedHex = key == null ? null : solved?[key];
    if (solvedHex != null) {
      final form = slot['form'] as String;
      if (form == 'hex') return solvedHex;
      final rgb = hexToRgb(solvedHex);
      return '${rgb[0]}, ${rgb[1]}, ${rgb[2]}';
    }
    final family = slot['family'] as String;
    final baseAnchor = template.anchors[family]!;
    final paletteAnchor = anchors[family]!;
    final form = slot['form'] as String;
    if (form == 'hex') {
      return transplant(slot['base'] as String, baseAnchor, paletteAnchor);
    }
    final base = slot['base'] as List;
    final baseHex = rgbToHex(base[0] as num, base[1] as num, base[2] as num);
    final derived = transplant(baseHex, baseAnchor, paletteAnchor);
    final rgb = hexToRgb(derived);
    return '${rgb[0]}, ${rgb[1]}, ${rgb[2]}';
  }

  // ── the contrast engine seam (grilled 2026-09-11) ──────────────────
  // The slot map every solve renders from: token name -> derived core
  // hex, plus every rule slot under its implicit key 'r<i>s<j>' (and a
  // template 'key' aliasing the rule's first slot). The pasted anchors
  // never enter this map — they are inviolate by construction; every
  // value here is a transplant output the solver may move.
  Map<String, String> _slotHexes(
      Map<String, String> anchors, PaletteTemplate template) {
    final map = <String, String>{};
    for (final token in template.tokens) {
      map[token['name'] as String] =
          _slotCoreHex(token, anchors, template);
    }
    for (var i = 0; i < template.rules.length; i++) {
      final slots = (template.rules[i]['slots'] as List).cast<Map>();
      for (var j = 0; j < slots.length; j++) {
        map['r${i}s$j'] = _slotCoreHex(
            Map<String, Object?>.from(slots[j]), anchors, template);
      }
      final key = template.rules[i]['key'];
      if (key is String && slots.isNotEmpty) {
        map[key] = map['r${i}s0']!;
      }
    }
    return map;
  }

  String _slotCoreHex(Map<String, Object?> slot,
      Map<String, String> anchors, PaletteTemplate template) {
    final family = slot['family'] as String;
    final baseAnchor = template.anchors[family]!;
    final paletteAnchor = anchors[family]!;
    final base = slot['base'];
    if (base is String) return transplant(base, baseAnchor, paletteAnchor);
    final b = base as List;
    return transplant(
        rgbToHex(b[0] as num, b[1] as num, b[2] as num),
        baseAnchor,
        paletteAnchor);
  }

  /// The alias -> implicit-key map ('preloader-text' -> 'r4s0'): the
  /// contract may speak readable keys, but ONE key space — implicit —
  /// feeds the solver, the flip candidates, and the renderer, so a move
  /// can never land on an alias the renderer doesn't read.
  Map<String, String> _aliasMap(PaletteTemplate template) => {
        for (var i = 0; i < template.rules.length; i++)
          if (template.rules[i]['key'] is String)
            template.rules[i]['key'] as String: 'r${i}s0',
      };

  /// Expand the template's contract into concrete pairs: the explicit
  /// list (aliases canonicalized to implicit keys) plus familyPairs
  /// crossed over solid text rules (color:) × surface rules (background:)
  /// and mapped surface tokens. rgba-form text slots are the decorative
  /// ghosts — they never enter familyPairs.
  List<ContrastPair> _expandedPairs(PaletteTemplate template) {
    final aliases = _aliasMap(template);
    String canon(String k) => aliases[k] ?? k;
    final pairs = [
      for (final p0 in template.pairs)
        ContrastPair(
            fg: canon(p0.fg), bg: canon(p0.bg), level: p0.level,
            fgAlpha: p0.fgAlpha)
    ];
    if (template.familyPairs.isEmpty) return pairs;
    for (var i = 0; i < template.rules.length; i++) {
      final rule = template.rules[i];
      final tpl = (rule['tpl'] as String).trimLeft();
      final slots = (rule['slots'] as List);
      if (slots.isEmpty || !tpl.startsWith('color:')) continue;
      final first = Map<String, Object?>.from(slots.first as Map);
      if (first['form'] != 'hex') continue; // ghost — exempt
      final fgFam = first['family'] as String;
      for (final fp in template.familyPairs) {
        if (fp.fg != fgFam) continue;
        for (var k = 0; k < template.rules.length; k++) {
          final srule = template.rules[k];
          final stpl = (srule['tpl'] as String).trimLeft();
          if (!stpl.startsWith('background')) continue;
          final ss = (srule['slots'] as List);
          if (ss.isEmpty) continue;
          final sslot = Map<String, Object?>.from(ss.first as Map);
          if (sslot['form'] != 'hex') continue;
          if (!fp.on.contains(sslot['family'])) continue;
          pairs.add(ContrastPair(fg: 'r${i}s0', bg: 'r${k}s0', level: fp.level));
        }
        for (final fam in fp.on) {
          final token = template.surfaces[fam];
          if (token != null && template.tokens.any((t) => t['name'] == token)) {
            pairs.add(ContrastPair(fg: 'r${i}s0', bg: token, level: fp.level));
          }
        }
      }
    }
    return pairs;
  }

  /// Solve the slot map against the contract (solve:false = MANUAL: the
  /// raw transplant map ships, the editor/gate own the visibility). The
  /// flip candidates: rule text slots and non-surface ink tokens may
  /// INVERT POLARITY (dark-family derivation <-> paper-family) — the
  /// palette's surfaces are its character; a mid-dark surface gets light
  /// text, never a bleach.
  ({Map<String, String> hexes, List<SolveMove> moves, List<String> unsolved})
      _solvedSlots(Map<String, String> anchors, PaletteTemplate template,
          {required bool solve}) {
    final raw = _slotHexes(anchors, template);
    if (!solve || template.pairs.isEmpty && template.familyPairs.isEmpty) {
      return (hexes: raw, moves: const [], unsolved: const []);
    }
    final surfaceTokens = template.surfaces.values.toSet();
    String? flipCandidate(String slot) {
      final isRule = slot.startsWith('r');
      final isToken = template.tokens.any((t) => t['name'] == slot);
      if (!isRule && !(isToken && !surfaceTokens.contains(slot))) return null;
      Map<String, Object?>? slotDef;
      if (isRule) {
        final m = RegExp(r'r(\d+)s(\d+)$').firstMatch(slot);
        if (m == null) return null;
        final rule = template.rules[int.parse(m.group(1)!)];
        final slots = (rule['slots'] as List);
        final j = int.parse(m.group(2)!);
        if (j >= slots.length) return null;
        slotDef = Map<String, Object?>.from(slots[j] as Map);
      } else {
        slotDef = Map<String, Object?>.from(
            template.tokens.firstWhere((t) => t['name'] == slot));
      }
      final family = slotDef['family'] as String;
      final opposite = family == 'dark' ? 'paper' : 'dark';
      final target = anchors[opposite];
      if (target == null) return null;
      final baseAnchor = template.anchors[family];
      if (baseAnchor == null) return null;
      final base = slotDef['base'];
      if (base is String) return transplant(base, baseAnchor, target);
      final b = base as List;
      return transplant(
          rgbToHex(b[0] as num, b[1] as num, b[2] as num),
          baseAnchor,
          target);
    }

    final (hexes, moves, unsolved) = solveContrast(
        slotHexes: raw,
        pairs: _expandedPairs(template),
        alt: flipCandidate);
    return (hexes: hexes, moves: moves, unsolved: unsolved);
  }

  String _tokenValue(Map<String, Object?> token, Map<String, String> anchors,
      PaletteTemplate template,
      [Map<String, String>? solved]) {
    final family = token['family'] as String;
    final baseAnchor = template.anchors[family]!;
    final paletteAnchor = anchors[family]!;
    final form = token['form'] as String;
    // The contrast engine's solved hex rides first — the alpha and shadow
    // forms re-derive their rgb from it, keeping the soft/ghost depth.
    final solvedHex = solved?[token['name'] as String];
    String derivedHex() {
      if (solvedHex != null) return solvedHex;
      final base = token['base'];
      if (base is String) return transplant(base, baseAnchor, paletteAnchor);
      final b = base as List;
      return transplant(rgbToHex(b[0] as num, b[1] as num, b[2] as num),
          baseAnchor, paletteAnchor);
    }

    if (form == 'hex') return derivedHex();
    if (form.startsWith('rgba:')) {
      final rgb = hexToRgb(derivedHex());
      return 'rgba(${rgb[0]}, ${rgb[1]}, ${rgb[2]}, ${form.substring(5)})';
    }
    if (form.startsWith('shadow:')) {
      final rgb = hexToRgb(derivedHex());
      return form
          .substring(7)
          .replaceAll('{t}', '${rgb[0]}, ${rgb[1]}, ${rgb[2]}');
    }
    throw StateError('unknown token form: $form');
  }

  /// Paste-a-Coolors-link (grilled Q5/Q6): derive, generate the override
  /// sheet, append the tokens.css var block, extend the manifest. A repeat
  /// paste of the same five hexes returns the existing entry — no dupes.
  PaletteEntry ingest(String url) {
    final manifest = PaletteManifest.load(artifactDir);
    if (manifest == null) {
      throw StateError('this artifact declares no palette plane');
    }
    final template = PaletteTemplate.load(artifactDir);
    if (template == null) {
      throw StateError('palette template missing — regenerate the design');
    }
    final parsed = parseCoolorsSlug(url);
    if (parsed == null) {
      throw ArgumentError('not a Coolors link — expected coolors.co/<5 hexes>');
    }
    // Slug hexes arrive bare ('10002b'); the whole plane speaks '#'-prefixed
    // (ids strip it with substring(1), themeColor keeps it, swatches match
    // the seeded entries' shape).
    final hexes = [for (final h in parsed) '#$h'];
    final wanted = ([...hexes]..sort()).join('-');
    final anchors = anchorsFor(hexes);
    for (final e in manifest.palettes) {
      final have =
          ([...e.swatch.map((s) => s.toLowerCase())]..sort()).join('-');
      if (have == wanted) {
        // Dedup — but a crash or manual cleanup between the artifact
        // writes can leave the entry pointing at a missing sheet or a
        // stripped tokens block (the c-2e1f27 half-wipe, ADDENDUM 18).
        // Repair in place instead of returning a hollow card.
        if (!_artifactsIntact(e)) renderArtifacts(e, anchors, template);
        return e;
      }
    }
    var id = 'c-${anchors['dark']!.substring(1)}';
    var n = 2;
    while (manifest.declares(id)) {
      id = 'c-${anchors['dark']!.substring(1)}-$n';
      n++;
    }

    final entry = PaletteEntry(
      id: id,
      name: 'Coolors ${anchors['dark']!.substring(1).toUpperCase()}',
      swatch: hexes,
      themeColor: anchors['accent']!,
      source: url,
      sheet: '/assets/styles/palettes/palette-$id.css',
    );
    renderArtifacts(entry, anchors, template);
    manifest.palettes.add(entry);
    manifest.save(artifactDir);
    _sweepCustomSlot(entry.id);
    return entry;
  }

  /// The one-custom-slot law (operator, 2026-09-02): the plane carries the
  /// seeded picks plus exactly ONE custom slot — a genuinely new entry
  /// REPLACES the previous custom, stripping its sheet and tokens block
  /// through the same deletion path the dial's × uses. Dedup hits return
  /// early and never reach this sweep.
  void _sweepCustomSlot(String keepId) {
    final stale = PaletteManifest.load(artifactDir)!
        .palettes
        .where((e) => !e.seeded && e.id != keepId)
        .map((e) => e.id)
        .toList();
    for (final id in stale) {
      delete(id);
    }
  }

  /// True when the entry's sheet file and tokens.css block both exist.
  bool _artifactsIntact(PaletteEntry e) {
    final sheet = e.sheet;
    if (sheet != null) {
      if (!File(p.join(artifactDir, sheet.replaceFirst('/', '')))
          .existsSync()) {
        return false;
      }
    }
    final tokensFile = File(tokensCssPath(artifactDir));
    if (!tokensFile.existsSync()) return false;
    return tokensFile
        .readAsStringSync()
        .contains('[data-palette="${e.id}"]');
  }

  /// Write (or rewrite) the entry's two artifacts: the generated override
  /// sheet and the appended tokens.css var block (the ingest/birth path).
  void renderArtifacts(PaletteEntry entry, Map<String, String> anchors,
      PaletteTemplate template,
      {bool solve = true}) {
    renderSheet(entry, anchors, template, solve: solve);
    final tokensFile = File(tokensCssPath(artifactDir));
    tokensFile.parent.createSync(recursive: true);
    tokensFile.writeAsStringSync(
        _tokensBlock(entry, anchors, template, solve: solve),
        mode: FileMode.append);
  }

  /// The override sheet, written atomically (temp file + rename): update
  /// rewrites a sheet the manifest ALREADY points at, and a crash
  /// mid-write must never leave a truncated one referenced (the crash
  /// law). The path derives from the id — sheet fields name it by
  /// construction.
  void renderSheet(PaletteEntry entry, Map<String, String> anchors,
      PaletteTemplate template,
      {bool solve = true}) {
    final id = entry.id;
    final hexes = entry.swatch;
    final solved = _solvedSlots(anchors, template, solve: solve);
    // the override sheet — the solve log rides INSIDE the header comment
    // (leaked log lines would be invalid CSS and pollute the P5 reader).
    final buf = StringBuffer()
      ..writeln(
          '/* palette-$id.css — GENERATED override sheet (VERIFY ADDENDUM 17,')
      ..writeln(
          '   pasted Coolors ${hexes.join('-')}). Derived by the transplant law;')
      ..writeln(
          '   see assets/styles/palettes/_template.json.');
    if (solved.moves.isNotEmpty) {
      buf
        ..writeln('   contrast: WCAG 2.2 AA solved at render — '
            '${solved.moves.length} move(s):')
        ..writeAll([for (final m in solved.moves) '     $m\n']);
    }
    if (solved.unsolved.isNotEmpty) {
      buf.writeln(
          '   contrast: UNSOLVED after solve (extreme ramp): '
          '${solved.unsolved.join('; ')}');
    }
    buf
      ..writeln('   Do not hand-edit. */')
      ..writeln();
    for (final rule in template.rules) {
      final at = [for (final a in rule['at'] as List) '$a'];
      final sel = (rule['sel'] as String).replaceAll('{id}', id);
      var tpl = rule['tpl'] as String;
      final slots = rule['slots'] as List;
      final ri = template.rules.indexOf(rule);
      for (var i = 0; i < slots.length; i++) {
        tpl = tpl.replaceAll('{$i}',
            _derive(Map<String, Object?>.from(slots[i] as Map), anchors,
                template, solved.hexes, 'r${ri}s$i'));
      }
      final ind = '  ' * at.length;
      for (var k = 0; k < at.length; k++) {
        buf.writeln('${'  ' * k}${at[k]} {');
      }
      buf
        ..writeln('$ind$sel {')
        ..writeln('$ind  $tpl')
        ..writeln('$ind}');
      for (var k = at.length - 1; k >= 0; k--) {
        buf.writeln('${'  ' * k}}');
      }
      buf.writeln();
    }
    final sheet = File(p.join(
        artifactDir, 'assets', 'styles', 'palettes', 'palette-$id.css'));
    sheet.parent.createSync(recursive: true);
    final tmp = File('${sheet.path}.tmp');
    tmp.writeAsStringSync(buf.toString());
    tmp.renameSync(sheet.path);
  }

  /// One entry's tokens.css var block text (appended on birth; deletion
  /// and update strip by id).
  String _tokensBlock(PaletteEntry entry, Map<String, String> anchors,
      PaletteTemplate template,
      {bool solve = true}) {
    final id = entry.id;
    final hexes = entry.swatch;
    final solved = _solvedSlots(anchors, template, solve: solve);
    final tokens = StringBuffer()
      ..writeln()
      ..writeln(
          '/* pasted palette $id (${hexes.join('-')}) — ingestion, do not hand-edit */')
      ..writeln('[data-palette="$id"] {');
    for (final token in template.tokens) {
      tokens.writeln(
          '  ${token['name']}: ${_tokenValue(token, anchors, template, solved.hexes)};');
    }
    tokens.writeln('}');
    return tokens.toString();
  }

  /// Strip + append in ONE write (the update law): the old block goes and
  /// the re-derived block lands together — there is no crash window
  /// between two writes because there is only one.
  void replaceTokensBlock(PaletteEntry entry, Map<String, String> anchors,
      PaletteTemplate template,
      {bool solve = true}) {
    final tokensFile = File(tokensCssPath(artifactDir));
    final current =
        tokensFile.existsSync() ? tokensFile.readAsStringSync() : '';
    tokensFile.parent.createSync(recursive: true);
    tokensFile.writeAsStringSync(
        stripTokensBlock(current, entry.id) +
            _tokensBlock(entry, anchors, template, solve: solve));
  }

  /// Deletion is a dial action (grilled Q13): non-seeded entries only —
  /// the shipped palettes stay. The default can never be deleted. Returns
  /// the remaining entries.
  List<PaletteEntry> delete(String id) {
    final manifest = PaletteManifest.load(artifactDir);
    if (manifest == null) {
      throw StateError('this artifact declares no palette plane');
    }
    final entry = manifest.palettes.where((e) => e.id == id).firstOrNull;
    if (entry == null) throw ArgumentError('no such palette: $id');
    if (entry.seeded || id == manifest.defaultId) {
      throw ArgumentError('the shipped palettes stay — only pasted ones go');
    }
    manifest.palettes.removeWhere((e) => e.id == id);
    if (entry.sheet != null) {
      final f = File(p.join(artifactDir, entry.sheet!.replaceFirst('/', '')));
      if (f.existsSync()) f.deleteSync();
    }
    final tokensFile = File(tokensCssPath(artifactDir));
    if (tokensFile.existsSync()) {
      tokensFile.writeAsStringSync(
          stripTokensBlock(tokensFile.readAsStringSync(), id));
    }
    manifest.save(artifactDir);
    return manifest.palettes;
  }

  /// In-dial editing (grilled Q4): 3..7 hexes, each a valid 6-digit hex —
  /// the engine accepts 1..7 but the manifest floors at 3 (the dial law).
  /// Editing the DEFAULT palette FORKS into the one custom slot (the base
  /// corpus stays hand-owned); any other palette edits IN PLACE — stable
  /// id, so published picks and ?palette= links never break. A swatch set
  /// identical to another palette's refuses, naming the conflict
  /// (PaletteConflictError). Artifacts land before the manifest saves
  /// (the crash law, unchanged).
  ({PaletteEntry entry, bool forked, List<PaletteEntry> palettes}) update(
      String id, List<String> hexes,
      {String? name, bool? auto}) {
    final manifest = PaletteManifest.load(artifactDir);
    if (manifest == null) {
      throw StateError('this artifact declares no palette plane');
    }
    final template = PaletteTemplate.load(artifactDir);
    if (template == null) {
      throw StateError('palette template missing — regenerate the design');
    }
    if (hexes.length < 3 || hexes.length > 7) {
      throw ArgumentError('3..7 hexes, got ${hexes.length}');
    }
    final normalized = <String>[];
    for (final h in hexes) {
      try {
        normalized.add(normHex(h));
      } on FormatException catch (e) {
        throw ArgumentError(e.message);
      }
    }
    // The sorted-lowercase swatch-set compare, one law with ingest.
    String keyOf(List<String> swatch) =>
        ([...swatch.map((s) => s.toLowerCase())]..sort()).join('-');
    final wanted = keyOf(normalized);
    final anchors = anchorsForN(normalized);
    if (id == manifest.defaultId) {
      // FORK (Q4): dedup against ALL entries — a fork duplicating any
      // palette (the default included) refuses, naming the conflict.
      for (final e in manifest.palettes) {
        if (keyOf(e.swatch) == wanted) throw PaletteConflictError(e.id);
      }
      var forkId = 'c-${anchors['dark']!.substring(1)}';
      var n = 2;
      while (manifest.declares(forkId)) {
        forkId = 'c-${anchors['dark']!.substring(1)}-$n';
        n++;
      }
      final entry = PaletteEntry(
        id: forkId,
        name: name ?? 'Custom ${anchors['dark']!.substring(1).toUpperCase()}',
        swatch: normalized,
        themeColor: anchors['accent']!,
        source: 'dial-edit:fork-of-$id',
        sheet: '/assets/styles/palettes/palette-$forkId.css',
        auto: auto ?? true,
      );
      renderArtifacts(entry, anchors, template, solve: entry.auto);
      manifest.palettes.add(entry);
      manifest.save(artifactDir);
      _sweepCustomSlot(entry.id);
      return (
        entry: entry,
        forked: true,
        palettes: PaletteManifest.load(artifactDir)!.palettes,
      );
    }
    // IN PLACE (Q4): dedup against the OTHER entries; id/seeded/source/
    // sheet untouched; swatch/themeColor (and name when given) re-derived.
    final index = manifest.palettes.indexWhere((e) => e.id == id);
    if (index < 0) throw ArgumentError('no such palette: $id');
    final old = manifest.palettes[index];
    for (final e in manifest.palettes) {
      if (e.id != id && keyOf(e.swatch) == wanted) {
        throw PaletteConflictError(e.id);
      }
    }
    if (old.sheet == null) {
      throw StateError(
          'palette $id declares no sheet — run arxa design palette-index');
    }
    final entry = PaletteEntry(
      id: old.id,
      name: name ?? old.name,
      swatch: normalized,
      themeColor: anchors['accent']!,
      seeded: old.seeded,
      source: old.source,
      sheet: old.sheet,
      auto: auto ?? old.auto,
    );
    renderSheet(entry, anchors, template, solve: entry.auto);
    replaceTokensBlock(entry, anchors, template, solve: entry.auto);
    manifest.palettes[index] = entry;
    manifest.save(artifactDir);
    return (entry: entry, forked: false, palettes: manifest.palettes);
  }

  /// Re-solve (the editor's Re-solve button, grilled Q5): re-render the
  /// palette through the contrast engine with solving ON and mark it
  /// AUTO again. The author's live voice — same id, same swatch, the
  /// contracted pairs pass once more.
  ({PaletteEntry entry, List<PaletteEntry> palettes, List<String> unsolved})
      resolve(String id) {
    final manifest = PaletteManifest.load(artifactDir);
    if (manifest == null) {
      throw StateError('this artifact declares no palette plane');
    }
    final template = PaletteTemplate.load(artifactDir);
    if (template == null) {
      throw StateError('palette template missing — regenerate the design');
    }
    final index = manifest.palettes.indexWhere((e) => e.id == id);
    if (index < 0) throw ArgumentError('no such palette: $id');
    final old = manifest.palettes[index];
    if (old.sheet == null) {
      throw StateError(
          'palette $id declares no sheet — run arxa design palette-index');
    }
    final anchors = anchorsForN(old.swatch);
    final entry = PaletteEntry(
      id: old.id,
      name: old.name,
      swatch: old.swatch,
      themeColor: anchors['accent'] ?? old.themeColor,
      seeded: old.seeded,
      source: old.source,
      sheet: old.sheet,
      auto: true,
    );
    final solved = _solvedSlots(anchors, template, solve: true);
    renderSheet(entry, anchors, template, solve: true);
    replaceTokensBlock(entry, anchors, template, solve: true);
    manifest.palettes[index] = entry;
    manifest.save(artifactDir);
    return (
      entry: entry,
      palettes: manifest.palettes,
      unsolved: solved.unsolved,
    );
  }
}

// ── the deployed-dial bake ───────────────────────────────────────────────

/// Resolve everything the ejected worker needs for the static palette/dial
/// channel (grilled Q7-Q10): the manifest object, the publishable-key
/// channel (the SERVICE key never ships), the design's registered id, the
/// published palette, and the author token's SHA-256. Null when the
/// artifact declares no palettes; a manifest-only bake when the Supabase
/// channel is under-configured (the deployed site still stamps
/// data-palette and serves /palettes.json — no dial, no live publish).
class DeployedDialBake {
  DeployedDialBake._(this._url, this._serviceKey);

  final String _url;
  final String _serviceKey;

  // The dial's network discipline (arxa_dial.dart, 2026-08-25): timeouts
  // convert a stall into a fast failure, never a held socket.
  final HttpClient _http = HttpClient()
    ..connectionTimeout = const Duration(seconds: 5)
    ..idleTimeout = const Duration(seconds: 30);

  Future<(int, String)> _req(String method, String path,
      {Object? body, Map<String, String>? headers}) async {
    final request = await _http
        .openUrl(method, Uri.parse('$_url/rest/v1/$path'))
        .timeout(const Duration(seconds: 8));
    request.headers.set('apikey', _serviceKey);
    request.headers.set('Authorization', 'Bearer $_serviceKey');
    headers?.forEach(request.headers.set);
    if (body != null) {
      request.headers.contentType = ContentType.json;
      request.write(jsonEncode(body));
    }
    final res = await request.close().timeout(const Duration(seconds: 10));
    return (res.statusCode, await utf8.decoder.bind(res).join());
  }

  Future<String> _designId(String project, String artifact) async {
    final get = await _req('GET',
        'arxa_dial_designs?project=eq.${Uri.encodeComponent(project)}&artifact=eq.${Uri.encodeComponent(artifact)}&select=id');
    if (get.$1 < 300) {
      final rows = jsonDecode(get.$2);
      if (rows is List && rows.isNotEmpty && rows.first is Map) {
        final id = (rows.first as Map)['id'];
        if (id is String) return id;
      }
    }
    final post = await _req('POST', 'arxa_dial_designs',
        body: {'project': project, 'artifact': artifact},
        headers: {'Prefer': 'return=representation'});
    if (post.$1 < 300) {
      final rows = jsonDecode(post.$2);
      if (rows is List && rows.isNotEmpty && rows.first is Map) {
        final id = (rows.first as Map)['id'];
        if (id is String) return id;
      }
    }
    // The 409 race (two first-ejects at once): the row provably exists —
    // read it back.
    return _designId(project, artifact);
  }

  static Future<Map<String, Object?>?> resolve({
    required String artifactDir,
    required String project,
    required String artifact,
    Map<String, String>? env,
    String? credentialsFileText,
  }) async {
    final manifest = PaletteManifest.load(artifactDir);
    if (manifest == null) return null;
    final environment = env ?? Platform.environment;
    String? url = environment['ARXA_SUPABASE_URL'];
    String? serviceKey = environment['ARXA_SUPABASE_SERVICE_KEY'];
    String? publishableKey = environment['ARXA_SUPABASE_PUBLISHABLE_KEY'];
    if (credentialsFileText != null) {
      for (final line in credentialsFileText.split('\n')) {
        final m = RegExp(r'^(url|service_key|publishable_key)=(.+)$')
            .firstMatch(line.trim());
        if (m == null) continue;
        if (m.group(1) == 'url') url ??= m.group(2)!.trim();
        if (m.group(1) == 'service_key') serviceKey ??= m.group(2)!.trim();
        if (m.group(1) == 'publishable_key') {
          publishableKey ??= m.group(2)!.trim();
        }
      }
    }
    final manifestJson = <String, Object?>{
      'version': 1,
      'default': manifest.defaultId,
      'palettes': [for (final e in manifest.palettes) e.toJson()],
    };
    if (url == null ||
        url.isEmpty ||
        serviceKey == null ||
        serviceKey.isEmpty ||
        publishableKey == null ||
        publishableKey.isEmpty) {
      stderr.writeln('[eject] palette plane: manifest baked, dial channel '
          'off (ARXA_SUPABASE_URL + ARXA_SUPABASE_SERVICE_KEY + '
          'ARXA_SUPABASE_PUBLISHABLE_KEY required) — the deployed site '
          'stamps data-palette but ships no dial and no live publish.');
      return {'manifest': manifestJson, 'static': null, 'mintedAuthorToken': null};
    }
    final bake = DeployedDialBake._(url, serviceKey);
    final designId = await bake._designId(project, artifact);
    var published = manifest.defaultId;
    Map<String, String>? fontCell;
    final axes = await bake._req('GET',
        'arxa_dial_axes?design_id=eq.$designId&select=palette,font');
    if (axes.$1 < 300) {
      final rows = jsonDecode(axes.$2);
      if (rows is List && rows.isNotEmpty && rows.first is Map) {
        final pickCell = (rows.first as Map)['palette'];
        if (pickCell is String && manifest.declares(pickCell)) {
          published = pickCell;
        }
        // The font plane (grilled 2026-09-13): bake the published per-role
        // picks; the worker re-validates each against the baked manifest
        // (an id ahead of this deploy falls to the default, ADDENDUM 18's
        // font twin).
        final f = (rows.first as Map)['font'];
        if (f is Map) {
          fontCell = {
            for (final e in f.entries)
              if (e.key is String && e.value is String)
                e.key as String: e.value as String,
          };
        }
      }
    }
    // The author token: env wins, the stored hash carries across ejects,
    // and a first eject mints + prints ONCE.
    String? authorTokenToPrint;
    String? existingHash;
    final row = await bake._req('GET',
        'arxa_dial_designs?id=eq.$designId&select=author_token_hash');
    if (row.$1 < 300) {
      final rows = jsonDecode(row.$2);
      if (rows is List && rows.isNotEmpty && rows.first is Map) {
        existingHash = (rows.first as Map)['author_token_hash'] as String?;
      }
    }
    final envToken = environment['ARXA_DIAL_AUTHOR_TOKEN'];
    final String authorSha;
    if (envToken != null && envToken.isNotEmpty) {
      authorSha = sha256.convert(ascii.encode(envToken)).toString();
    } else if (existingHash != null && existingHash.isNotEmpty) {
      authorSha = existingHash;
    } else {
      final token = base64Url
          .encode(List<int>.generate(
              24, (_) => math.Random.secure().nextInt(256)))
          .replaceAll('=', '');
      authorSha = sha256.convert(ascii.encode(token)).toString();
      authorTokenToPrint = token;
    }
    if (authorSha != existingHash) {
      await bake._req('PATCH', 'arxa_dial_designs?id=eq.$designId',
          body: {'author_token_hash': authorSha});
    }
    return {
      'manifest': manifestJson,
      'static': {
        'artifact': artifact,
        'url': url,
        'anonKey': publishableKey,
        'designId': designId,
        'published': published,
        if (fontCell != null) 'font': fontCell,
        'authorSha256': authorSha,
      },
      'mintedAuthorToken': authorTokenToPrint,
      // The live instance (eject-bake reuse): readOverlay/clearOverlay
      // without a second resolve round trip.
      'bake': bake,
    };
  }

  // ── the Live Overlay eject bake (edit redesign, decision 7, 2026-09-11) ─

  /// Reads the design's live overlay row (the author's text + image edits
  /// that streamed to client dials since the last eject). Null = no row.
  Future<Map<String, dynamic>?> readOverlay(String designId) async {
    final r = await _req('GET',
        'arxa_dial_overlays?design_id=eq.$designId&select=patches,rev');
    if (r.$1 >= 300) return null;
    final rows = jsonDecode(r.$2);
    if (rows is! List || rows.isEmpty || rows.first is! Map) return null;
    final patches = (rows.first as Map)['patches'];
    if (patches is! Map || patches.isEmpty) return null;
    return Map<String, dynamic>.from(patches);
  }

  /// Clears the overlay row (save_overlay with empty patches = revert):
  /// called by the eject AFTER every patch baked into source, so live
  /// view and source converge at the deploy boundary.
  Future<bool> clearOverlay(String designId) async {
    final r = await _req('POST', 'rpc/save_overlay', body: {
      'p_design_id': designId,
      'p_link_token': '',
      'p_base_rev': 0x7fffffff, // never stale on a deliberate clear
      'p_patches': {},
    });
    if (r.$1 >= 300) return false;
    final decoded = jsonDecode(r.$2);
    return decoded is Map && decoded['ok'] == true;
  }
