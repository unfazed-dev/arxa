/// The OFFICIAL brand sign-in buttons. ROUTES THROUGH AdaptiveButton (with a
/// leading brand-glyph asset) so the CTA follows the render strategy like every
/// other control — native Liquid Glass on iOS, native Compose M3 Expressive on
/// Android, shadcn on web — instead of bypassing it with a flat Flutter button.
/// The brand marks are the official assets (bundled as assets/svg/brand_*.svg by
/// the factory; glass rasterizes them to the native UIButton, expressive draws them
/// via ExButton's Canvas BrandGlyph, shadcn renders SvgPicture.asset).
/// DESIGN-AGNOSTIC: the provider set comes from the design's go('<provider>')
/// buttons; onPressed runs the generated auth VM's go('<provider>') (Supabase).
class AdaptiveAuthButton extends StatelessWidget {
  const AdaptiveAuthButton({
    super.key,
    required this.provider,
    required this.label,
    required this.onPressed,
    this.busy = false,
  });
  final String provider;            // 'apple' | 'google'
  final String label;               // design-derived ("Continue with Apple")
  final VoidCallback? onPressed;
  final bool busy;

  @override
  Widget build(BuildContext context) {
    // Platform-suppression (DATA-DRIVEN): a provider whose native sign-in doesn't
    // exist on the current platform is suppressed entirely (SizedBox.shrink) so the
    // sign-in stack re-flows around the available providers. The allowlist is
    // _kProviderPlatforms (generated from BRAND_REGISTRY, mirroring the canonical
    // catalog's providerPlatformBindings) — NOT a hardcoded provider name, so adding
    // a platform-bound provider (e.g. a web-only OAuth) suppresses it with no code
    // edit here. The gap-collapse in generate_view.py (AdaptiveGap) drops the orphan
    // spacer. Providers absent from the map, or listed on all 3 platforms, always
    // render NATIVE via AdaptiveButton + the leading brand glyph.
    final allowed = _kProviderPlatforms[provider];
    if (allowed != null && !_strategyInPlatforms(currentStrategy(), allowed)) {
      return const SizedBox.shrink();
    }
    return AdaptiveButton(
      label: label,
      variant: AdaptiveButtonVariant.primary,
      // Google → white container (the brand-mandated G-on-white); Apple → ink (black).
      tint: provider == 'google' ? Colors.white : AppTokens.ink,
      // Google label dark-on-white; Apple label light-on-black.
      foreground: provider == 'google' ? AppTokens.ink : Colors.white,
      leadingIconAsset: _glyphAsset(provider),
      expand: true,
      busy: busy,
      onPressed: onPressed,
    );
  }

  // Maps a RenderStrategy to whether it's available for a provider's platform
  // allowlist. The strategy IS the platform at runtime (glass=iOS, expressive=
  // Android, shadcn=web/desktop), so a provider allowlist of ['ios'] suppresses
  // on expressive+shadcn. Kept here (not in render_strategy.dart) because the
  // mapping is provider-suppression vocabulary, not render vocabulary.
  static bool _strategyInPlatforms(RenderStrategy s, List<String> platforms) {
    switch (s) {
      case RenderStrategy.glass:
        return platforms.contains('ios');
      case RenderStrategy.expressive:
        return platforms.contains('android');
      case RenderStrategy.shadcn:
        return platforms.contains('web');
    }
  }

  // The bundled brand-glyph asset path per provider. Every brand mark is rasterized
  // to a PNG (assets/png/brand_{provider}.png) — the canonical asset every native
  // platform renders (iOS UIKit decode + Android Compose BitmapPainter), so the mark
  // is identical across platforms. No SVG/per-brand branching.
  static String _glyphAsset(String provider) => 'assets/png/brand_$provider.png';
}

// Maps a brand-glyph asset path → the provider name ExButton's Compose Image
// dispatches on ('google' / 'apple' / ...). Used by AdaptiveButton's expressive
// branch to pass params['glyph'] so Android loads brand_{name}.png natively.
String _providerFromAsset(String asset) {
  final m = RegExp(r'brand_([a-z]+)\.png').firstMatch(asset);
  return m?.group(1) ?? '';
}

// The brand's colorMode ('brand' | 'mono') from its asset path — tells the Compose
// Image whether to tint the mark to the button fg (mono: Apple/GitHub/X) or render
// its fixed brand colours (brand: Google/Microsoft/Facebook). The mono set is
// generated from the factory's BRAND_REGISTRY (see _kMonoBrandProviders above).
String _providerColorMode(String asset) {
  final provider = _providerFromAsset(asset);
  return _kMonoBrandProviders.contains(provider) ? 'mono' : 'brand';
}

// True when the brand mark is monochrome (tinted to button fg). On iOS glass, mono
// marks render natively (the package's template tint = fg, which is what they want);
// brand-color marks (Google/Microsoft/Facebook) need a Flutter overlay to keep their
// original colours (the package forces template mode → would flatten to monochrome).
bool _glyphIsMono(String asset) =>
    _kMonoBrandProviders.contains(_providerFromAsset(asset));

