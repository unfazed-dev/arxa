// ──────────────────── _tplApp ────────────────────

String _tplApp(
    String appName,
    List screens,
    List platforms,
    List entities,
    Map<String, dynamic>? primaryNav) {
  final tabIds = (primaryNav?['tabs'] as List?)
          ?.map((t) => (t as Map)['id'] as String)
          .toSet() ??
      <String>{};
  final hasShell = tabIds.isNotEmpty;
  final topScreens = hasShell
      ? screens.where((s) => !tabIds.contains((s as Map)['id'])).toList()
      : screens;

  var imports = topScreens
      .map((s) =>
          "import '../presentation/${_snake((s as Map)['id'] as String)}_view.dart';")
      .join('\n');
  if (hasShell) {
    imports += "\nimport '../presentation/home_shell_view.dart';";
  }
  if (imports.isEmpty) imports = '// (no screens)';

  final hasAuth = topScreens.any((s) => (s as Map)['guard'] != null);
  final routeLines = <String>[];
  var shellInserted = false;
  var firstRoute = true;

  String route(String page, bool initial) =>
      '    MaterialRoute(page: $page${initial ? ', initial: true' : ''}),';

  for (final s in topScreens) {
    final sm = s as Map;
    final cls = _pascal(sm['id'] as String);
    final guard = sm['guard'] as Map?;
    final note = guard != null
        ? '  // guarded: ${guard['state']}=${guard['value']}'
        : null;
    if (hasShell && guard == null && !shellInserted) {
      final shellIsInitial = !hasAuth;
      routeLines.add(route('HomeShellView', shellIsInitial));
      shellInserted = true;
      if (shellIsInitial) firstRoute = false;
    }
    if (note != null) routeLines.add(note);
    final isInitial = firstRoute && (!hasShell || hasAuth);
    routeLines.add(route('${cls}View', isInitial));
    firstRoute = false;
  }
  if (hasShell && !shellInserted) {
    routeLines.add(route('HomeShellView', !hasAuth));
  }
  final routes =
      routeLines.isNotEmpty ? routeLines.join('\n') : '    // @stacked-route';

  final depList = <String>[
    'LazySingleton(classType: NavigationService)',
    'LazySingleton(classType: DialogService)',
    'LazySingleton(classType: SnackbarService)',
    'LazySingleton(classType: BottomSheetService)',
    'LazySingleton(classType: SupabaseAuthService)',
    'LazySingleton(classType: FeedbackService)',
  ];
  final repoImports = <String>[];
  for (final e in entities) {
    final em = e as Map;
    final en = _snake(em['name'] as String);
    final ec = _pascal(em['name'] as String);
    repoImports.add("import '../domain/ports/${en}_repository.dart';");
    repoImports
        .add("import '../infrastructure/${en}_repository_cached.dart';");
    depList.add(
        'LazySingleton(classType: ${ec}RepositoryCached, asType: ${ec}Repository)');
  }
  final deps = depList.join(',\n');
  final infraImport = [
    "import '../infrastructure/supabase_auth_service.dart';",
    ...repoImports,
  ].join('\n');
  final platComment =
      '// platforms in scope: ${platforms.map((p) => p.toString()).join(', ')}';

  return '$genMarker\n'
      '// $platComment\n'
      "import 'package:stacked/stacked_annotations.dart';\n"
      "import 'package:stacked_services/stacked_services.dart';\n"
      '\n'
      '$infraImport\n'
      "import '../ui/feedback_service.dart';\n"
      '$imports\n'
      '\n'
      '@StackedApp(\n'
      '  routes: [\n'
      '$routes\n'
      '    // @stacked-route\n'
      '  ],\n'
      '  dependencies: [\n'
      '      $deps,\n'
      '  ],\n'
      ')\n'
      'class App {}\n';
}

// ──────────────────── GOLDEN + PLAYBOOK + TOKENS ────────────────────

String _golden(Map<String, dynamic> breakdown,
    Map<String, dynamic> tokensTree, Map<String, dynamic> dataModel) {
  final payload = _sortedJsonEncode({
    'pages': breakdown['pages'] ?? [],
    'screenFlow': breakdown['screenFlow'] ?? [],
    'sharedComponents': breakdown['sharedComponents'] ?? [],
    'tokens': tokensTree,
    'dataModel': dataModel,
    'templates': templatesVersion,
  });
  return crypto.sha256(Uint8List.fromList(utf8.encode(payload)))
      .map((b) => b.toRadixString(16).padLeft(2, '0'))
      .join();
}

