class _RiseInState extends State<RiseIn> with SingleTickerProviderStateMixin {
  late final AnimationController _controller;
  late final Animation<double> _t;
  bool _started = false;

  @override
  void initState() {
    super.initState();
    final int total = widget.delayMs + widget.durationMs;
    _controller = AnimationController(
        vsync: this, duration: Duration(milliseconds: total));
    // hold faded/offset for delayMs, then run the design curve over durationMs
    _t = CurvedAnimation(
        parent: _controller,
        curve: Interval(widget.delayMs / total, 1.0, curve: widget.curve));
  }

  @override
  void dispose() {
    _controller.dispose();
    super.dispose();
  }

  // Start the cascade only once this view is the settled, visible foreground.
  // A view reached by replace/push is covered by the OUTGOING screen for
  // transitionDuration: if the cascade fires at build it runs (and largely
  // finishes) behind that screen, so the reveal shows elements already in place
  // — a pop, not a rise. So: if our own entrance is still animating in, start
  // when it completes; else (already placed, the previous screen animating out)
  // wait transitionDuration; else (no transition) start immediately.
  void _begin() {
    if (!mounted) return;
    final route = ModalRoute.of(context);
    final anim = route?.animation;
    if (anim != null && !anim.isCompleted && !anim.isDismissed) {
      void onStatus(AnimationStatus s) {
        if (s == AnimationStatus.completed) {
          anim.removeStatusListener(onStatus);
          if (mounted) _controller.forward();
        }
      }
      anim.addStatusListener(onStatus);
      return;
    }
    final d = route?.transitionDuration ?? Duration.zero;
    if (d == Duration.zero) {
      _controller.forward();
    } else {
      // ponytail: this also defers the app's FIRST route by transitionDuration —
      // a no-splash design shows ~td of placed-but-faded content before the
      // cascade. Harmless when a splash precedes (its hold absorbs the wait,
      // verified on atlet). Upgrade path if it matters: track nav to tell a
      // cold-start initial route from one reached via push/replace (isFirst is
      // true for both after a replace, so it can't distinguish them).
      Future<void>.delayed(d, () {
        if (mounted) _controller.forward();
      });
    }
  }

  @override
  Widget build(BuildContext context) {
    if (widget.skipOnGlass && currentStrategy() == RenderStrategy.glass) {
      return widget.child;
    }
    if (!_started) {
      _started = true;
      WidgetsBinding.instance.addPostFrameCallback((_) => _begin());
    }
    return AnimatedBuilder(
      animation: _t,
      child: widget.child,
      builder: (context, c) => Opacity(
        opacity: _t.value.clamp(0.0, 1.0),
        child: Transform.translate(
            offset: Offset(0, (1 - _t.value) * widget.dy), child: c),
      ),
    );
  }
}

/// Defer a one-shot effect controller until this view is the settled foreground (not
/// still sliding in under a route transition) — else the motion plays behind the
/// incoming-screen animation and only the end state is seen. Same policy as
/// RiseIn._begin; shared by the design's one-shot effects (PulseRing/PopIn).
mixin _DeferredStart<T extends StatefulWidget> on State<T> {
  bool _kicked = false;
  void deferStart(AnimationController c) {
    if (_kicked) return;
    _kicked = true;
    WidgetsBinding.instance.addPostFrameCallback((_) {
      if (!mounted) return;
      final route = ModalRoute.of(context);
      final anim = route?.animation;
      if (anim != null && !anim.isCompleted && !anim.isDismissed) {
        void onStatus(AnimationStatus s) {
          if (s == AnimationStatus.completed) {
            anim.removeStatusListener(onStatus);
            if (mounted) c.forward();
          }
        }
        anim.addStatusListener(onStatus);
        return;
      }
      final d = route?.transitionDuration ?? Duration.zero;
      if (d == Duration.zero) {
        c.forward();
      } else {
        Future<void>.delayed(d, () {
          if (mounted) c.forward();
        });
      }
    });
  }
}

