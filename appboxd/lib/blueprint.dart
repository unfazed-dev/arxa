              // The label↔chevron gap matches the design's `marginLeft: 6` (bundle.html:4023)
              // for trailing-affordance buttons; leading brand marks keep the package default
              // (8pt — the brand-glyph leading rhythm). The package's imagePadding applies to
              // both sides of its HStack, so this only branches on trailing-only buttons.
              imagePadding: (trailingSfSymbol != null && sfSymbol == null && leadingIconAsset == null)
                  ? 6
                  : 8,
              // enterOnAppear is held on AdaptiveButton for the native glass entrance
              // (GlassEntrance descriptor), but NOT forwarded to LiquidGlassButton —
              // native_liquid_glass has no enterOnAppear param yet (the mount hook that
              // flips `appeared` after delayMs is the one piece not in the package; see
              // glass_entrance.py). Forward-compat: the descriptor is stable, views
              // compile, and when the package adds the hook this line wires it.
            );
        // Feed the platform view a BOUNDED width. A UiKitView has no intrinsic size, so
        // width:null in a loose Row (the "Your workouts" header) lets the native view size
        // async + drift/grow across route transitions — that is the "New button moved" bug.
        // expand → parent width; content buttons → a deterministic estimate (mirrors the
        // expressive path; ~132px for "New") so the slot is fully bounded and stable. Same
        // no-intrinsic-size-platform-view principle as AdaptiveIconButton's SizedBox.square.
        // The glyph renders in the native icon slot (PNG, original/template via
        // iconRenderingMode) — icon + label are both native in one UiKitView, so alignment
        // is the LiquidGlassButton's own HStack. No Flutter overlay (the spacer-slot hack
        // is gone — the forked package renders brand colors natively).
        if (expand) {
          return LayoutBuilder(
            builder: (c, cons) =>
                glass(cons.maxWidth.isFinite ? cons.maxWidth : null));
        }
        return glass(label.length * 12.0 + 96);
      case RenderStrategy.expressive:
        // All non-busy buttons → TRUE Compose Material 3 (a real native primitive,
        // not a Flutter widget). Content-width buttons size via the measure
        // round-trip: Compose reports its content width and _ExpressiveView tightens
        // the AndroidView. Busy → Flutter spinner fallback (flagged): the
        // disabled+spinner state needs no native fidelity and skips a busy channel push.
        if (!busy) {
          final params = <String, dynamic>{
            'kind': 'button',
            'label': label,
            'variant': variant.name,
            'tint': resolvedTint.toARGB32(),
            'fg': resolvedForeground.toARGB32(),
            'enabled': enabled, // native Compose dimming + tap-ignore (the validity gate)
            'trailing': trailingSfSymbol, // a trailing affordance (the design's Send-code ›)
            'trailingIconSize': trailingSfSymbol != null ? trailingIconSize : null, // design token 14
            // A leading brand glyph (social CTA): the provider name + its colorMode →
            // ExButton's Compose Image (loads brand_{name}.png from the asset bundle,
            // tinted to fg when colorMode=='mono'). Null → no glyph.
            'glyph': leadingIconAsset != null
                ? _providerFromAsset(leadingIconAsset!)
                : null,
            'glyphColorMode': leadingIconAsset != null
                ? _providerColorMode(leadingIconAsset!)
                : null,
            'wrap': !expand,
          };
          void onPressedCb(String m, dynamic a) {
            if (m == 'onPressed') onPressed?.call();
          }
          // A11Y/PARITY: the Compose button renders its own label visually, but a native
          // AndroidView is an opaque node to Flutter's accessibility bridge — without a
          // Semantics wrapper the label never reaches the Android accessibility tree, so
          // uiautomator (the parity gate's adb_ui_tree source) and TalkBack can't see it.
          // The iOS LiquidGlassButton UiKitView bridges its AXLabel for free; the Android
          // path needs this explicit wrap so both platforms expose the same label. This is
          // what lets parity.py's text-parity gate VERIFY the native M3 buttons rendered.
          Widget wrap(Widget child) => Semantics(
              button: true, enabled: cb != null, label: label, child: child);
          if (expand) {
            return wrap(_ExpressiveView(
                params: params, width: null, height: 52, onMethod: onPressedCb));
          }
          // content-width estimate (must be ≥ content so the native button can wrap
          // inside it; glyphs + M3 padding + room for an icon). Shrinks to the
          // native-measured width on the first frame via the size round-trip.
          return wrap(_ExpressiveView(
            params: params,
            width: label.length * 12.0 + 96,
            height: 52,
            wrap: true,
            onMethod: onPressedCb,
          ));
        }
        final child = busy
            ? const SizedBox(
                height: 18, width: 18,
                child: CircularProgressIndicator(strokeWidth: 2))
            : Text(label);
        final b = switch (variant) {
          AdaptiveButtonVariant.primary => FilledButton(
              onPressed: cb,
              style: FilledButton.styleFrom(
                backgroundColor: resolvedTint,
                foregroundColor: resolvedForeground,
                shape: const StadiumBorder(),
                minimumSize: const Size(0, 52),
                padding:
                    const EdgeInsets.symmetric(horizontal: 24, vertical: 14),
              ),
              child: child,
            ),
          AdaptiveButtonVariant.secondary =>
            FilledButton.tonal(onPressed: cb, child: child),
          AdaptiveButtonVariant.outline =>
            OutlinedButton(onPressed: cb, child: child),
          AdaptiveButtonVariant.ghost => TextButton(onPressed: cb, child: child),
          // destructive busy-fallback: a high-emphasis red CTA (Sign out / Cancel
          // subscription). Tinted with the semantic danger token so it reads as
          // destructive (AppTokens.danger, aliased as _kFeedbackError).
          AdaptiveButtonVariant.destructive => FilledButton(
              onPressed: cb,
              style: FilledButton.styleFrom(
                backgroundColor: _kFeedbackError,
                foregroundColor: Colors.white,
                shape: const StadiumBorder(),
                minimumSize: const Size(0, 52),
                padding:
                    const EdgeInsets.symmetric(horizontal: 24, vertical: 14),
              ),
              child: child,
            ),
        };
        return expand ? SizedBox(width: double.infinity, child: b) : b;
      case RenderStrategy.shadcn:
        final labelWidget = Text(label);
        // A leading brand glyph (social CTA) renders as the official SVG asset before
        // the label; a trailing affordance (the design's Send-code ›) renders as a
        // Material icon after. Null → label alone. A small Row so it all sits inline.
        final child = busy
            ? const SizedBox(
                height: 16, width: 16,
                child: CircularProgressIndicator(strokeWidth: 2))
            : Row(
                mainAxisSize: MainAxisSize.min,
                children: [
                  if (leadingIconAsset != null) ...[
                    // shadcn/web renders the official SVG (flutter_svg is exact in-browser).
                    // leadingIconAsset is the PNG sibling (brand_{name}.png); resolve the SVG
                    // sibling (brand_{name}.svg) so web shows the brand mark as crisp vector.
                    SvgPicture.asset(
                        leadingIconAsset!.replaceFirst('/png/', '/svg/').replaceFirst('.png', '.svg'),
                        width: 18, height: 18),
                    const SizedBox(width: 10),
                  ],
                  labelWidget,
                  if (trailingIcon != null) ...[
                    const SizedBox(width: 6),
                    Icon(trailingIcon, size: trailingIconSize), // design token (14), not 16
                  ],
                ],
              );
        final b = switch (variant) {
          AdaptiveButtonVariant.primary =>
            ShadButton(onPressed: cb, child: child),
          AdaptiveButtonVariant.secondary =>
            ShadButton.secondary(onPressed: cb, child: child),
          AdaptiveButtonVariant.outline =>
            ShadButton.outline(onPressed: cb, child: child),
          AdaptiveButtonVariant.ghost =>
            ShadButton.ghost(onPressed: cb, child: child),
          AdaptiveButtonVariant.destructive =>
            ShadButton.destructive(onPressed: cb, child: child),
        };
        return expand ? SizedBox(width: double.infinity, child: b) : b;
    }
  }
}

/// A vertical gap that collapses on families where an adjacent CTA is
/// platform-suppressed. DESIGN-AGNOSTIC: it knows only about the `expressive`
/// family (the one family that suppresses an auth CTA — Sign-in-with-Apple),
/// not about any provider. On glass/shadcn (no suppression) it renders the
/// captured design gap; on expressive it renders nothing, so the remaining
/// CTAs re-flow evenly with NO orphan spacer (the design's gap would otherwise
/// sit before a now-zero-size suppressed widget and throw off the centering).
///
/// The generator emits this IN PLACE OF a raw SizedBox(height:n) gap ONLY when
/// the gap precedes a form auth-button child (AdaptiveAuthButton) — i.e. the
/// one gap that can become orphaned by platform suppression. Every other
/// captured gap stays a plain SizedBox (no render-strategy coupling in the
/// generic path). This keeps the gap's visibility co-located with the SAME
/// decision (expressive-suppression) that hides the CTA, so collapse is atomic.
class AdaptiveGap extends StatelessWidget {
  const AdaptiveGap(this.height, {super.key});
  final double height;

  @override
  Widget build(BuildContext context) {
    // expressive = the family that suppresses a CTA → no gap. The other two
    // families render the design's captured gap verbatim.
    return currentStrategy() == RenderStrategy.expressive
        ? const SizedBox.shrink()
        : SizedBox(height: height);
  }
}

class AdaptiveIconButton extends StatelessWidget {
  const AdaptiveIconButton({
    super.key,
    required this.icon,
    required this.sfSymbol,
    this.onPressed,
    this.size = 36,
    this.tint,
    this.foreground,
    this.semanticLabel,
    this.lite = false,
  });
  final IconData icon;     // Material / shadcn glyph
  final String sfSymbol;   // SF Symbol name for the glass family
  final VoidCallback? onPressed;
  final double size;       // diameter of the disc
  final Color? tint;       // disc fill
  final Color? foreground; // glyph color
  final String? semanticLabel;
  // lite: render a flat Flutter ink disc instead of a native glass/Compose
  // platform view. NOT the default for icon buttons. A leaf icon-button is a
  // glass/expressive CANDIDATE (see docs/design-systems): leaves render NATIVE
  // even inside a lite scroll-list card — the native path below tight-boxes the
  // platform view so it cannot drift. Use lite only to force a flat disc by
  // design, or where a native leaf is genuinely unavailable. (Composite surfaces
  // and whole scroll-list ROWS — e.g. AdaptiveCard — are the things that go lite.)
  final bool lite;

  @override
  Widget build(BuildContext context) {
    final cb = onPressed;
    final fill = tint ?? AppTokens.ink;
    final fg = foreground ?? AppTokens.bone;
    if (lite) {
      return Semantics(
        button: true,
        label: semanticLabel,
        child: Material(
          color: fill,
          shape: const CircleBorder(),
          clipBehavior: Clip.antiAlias,
          child: InkWell(
            onTap: cb,
            customBorder: const CircleBorder(),
            child: SizedBox.square(
              dimension: size,
              child: Center(child: Icon(icon, size: size * 0.5, color: fg)),
            ),
          ),
        ),
      );
    }
    // NATIVE leaf control: glass icon-button (iOS), Compose FilledIconButton
    // (Android), ShadButton (web/desktop). A leaf platform view stays native even
    // inside a lite scroll-list card — the catalog rule is "leaves are native;
    // composite surfaces & whole rows are lite". The row-to-row drift once seen
    // here was NOT the platform-view scroll bug: a UiKitView/ComposeView has no
    // intrinsic size, so under a LOOSE cross-axis constraint (a center-aligned Row
    // whose height varies by row) it expanded and the disc rode high. The
    // SizedBox.square below pins a deterministic size×size slot on BOTH axes, so
    // the native disc centers identically in every row.
    final Widget native = switch (currentStrategy()) {
      // Icon-only circular glass button = the LiquidGlassButton.icon named
      // constructor (NOT label:'' — that's text mode; NOT the deprecated
      // LiquidGlassIconButton). prominentGlass (NOT the .icon default `glass`) =
      // the HIG treatment for a PRIMARY CTA: opaque tinted glass that stands out,
      // vs translucent secondary glass. `interactive` defaults true → press lensing.
      RenderStrategy.glass => LiquidGlassButton.icon(
            onPressed: cb ?? () {},
            icon: NativeLiquidGlassIcon.sfSymbol(sfSymbol),
            style: LiquidGlassButtonStyle.prominentGlass,
            size: size,
            iconSize: size * 0.5,
            tint: fill,
            iconColor: fg,
            tooltip: semanticLabel,
          ),
      // TRUE Compose M3 Expressive FilledIconButton (platform view, kind
      // 'iconButton'). One ComposeView per card — the native-per-primitive
      // mandate; list-perf pooling is a factory-wide call, not this widget's.
      RenderStrategy.expressive => _ExpressiveView(
            params: {
              'kind': 'iconButton',
              'tint': fill.toARGB32(),
              'fg': fg.toARGB32(),
              'icon': sfSymbol, // SF-symbol name → ExIconButton picks the Compose glyph
            },
            width: size,
            height: size,
            onMethod: (m, a) {
              if (m == 'onPressed') cb?.call();
            },
          ),
      RenderStrategy.shadcn => ShadButton(
            onPressed: cb,
            child: Icon(icon, size: size * 0.5, color: fg,
                semanticLabel: semanticLabel),
          ),
    };
    // Tight box → deterministic slot for the no-intrinsic-size platform view.
    return SizedBox.square(dimension: size, child: native);
  }
}

class AdaptiveCard extends StatelessWidget {
  const AdaptiveCard({
    super.key,
    required this.child,
    this.padding = const EdgeInsets.all(16),
    this.onTap,
    this.tint,
    this.lite = false,
    this.radius = 16,
  });
  final Widget child;
  final EdgeInsetsGeometry padding;
  final VoidCallback? onTap;
  final Color? tint;

  /// Scrolling list rows set lite:true → Flutter-drawn even under glass.
  /// Platform views (real Liquid Glass) jank inside long lists; reserve them for
  /// static surfaces (stat deck, headers). This is the hybrid policy.
  final bool lite;

  /// Corner radius of the card surface (design --r-md=16 / --r-lg=24).
  final double radius;

  @override
  Widget build(BuildContext context) {
    switch (currentStrategy()) {
      case RenderStrategy.glass:
        if (lite) return _soft(BorderRadius.circular(radius));
        return LiquidGlassContainer(
          config: LiquidGlassConfig(
            effect: LiquidGlassEffect.regular,
            shape: LiquidGlassEffectShape.rect,
            cornerRadius: radius,
            tint: tint,
            // A SOLID native-glass surface, not a see-through pane. Without a
            // backgroundColor the Liquid Glass material samples whatever iOS
            // composites behind the Flutter layer (per package docs), so the card
            // reads as a wrong/translucent backdrop and the deck's inter-card gap
            // shows it too. backgroundColor makes it an effectively solid-coloured
            // surface (the design's paper/ink/accent fill) with the glass material
            // and specular edge on top — the card the design actually specifies.
            backgroundColor: tint ?? AppTokens.color24,
            interactive: onTap != null,
          ),
          onTap: onTap,
          child: Padding(padding: padding, child: child),
        );
      case RenderStrategy.expressive:
        return Card(
          margin: EdgeInsets.zero,
          color: tint ?? AppTokens.color24,
          elevation: 1,
          surfaceTintColor: AppTokens.accent,
          shape: RoundedRectangleBorder(
              borderRadius: BorderRadius.circular(radius)),
          child: InkWell(
            onTap: onTap,
            borderRadius: BorderRadius.circular(radius),
            child: Padding(padding: padding, child: child),
          ),
        );
      case RenderStrategy.shadcn:
        return ShadCard(padding: padding, child: child);
    }
  }

  Widget _soft(BorderRadius radius) {
    return DecoratedBox(
      decoration: BoxDecoration(
        color: tint ?? AppTokens.color24,
        borderRadius: radius,
        border: Border.all(color: AppTokens.rule),
      ),
      child: Material(
        type: MaterialType.transparency,
        child: InkWell(
          onTap: onTap,
          borderRadius: radius,
          child: Padding(padding: padding, child: child),
        ),
      ),
    );
  }
}

class AdaptiveTextField extends StatelessWidget {
  const AdaptiveTextField({
    super.key,
    required this.controller,
    this.placeholder,
    this.obscure = false,
    this.keyboardType,
    this.errorText,
    this.onChanged,
    this.enabled = true,
  });
  final TextEditingController controller;
  final String? placeholder;
  final bool obscure;
  final TextInputType? keyboardType;

  /// Inline field error (Phase A). expressive surfaces it in its native
  /// InputDecoration; glass/shadcn have no native error slot → an inline message
  /// is appended below. A HUMAN string — never a raw error object. VM-driven
  /// (reactive): the ViewModel re-validates on onChanged and owns the error state.
  final String? errorText;

  /// Live-edit hook → the ViewModel (formValid / per-field error). This is the seam
  /// that lets a disabled CTA enable on valid input (ADR-0003: state lives in the VM).
  final ValueChanged<String>? onChanged;

  /// Disabled (e.g. while a form is submitting). The glass/expressive/shadcn fields
  /// all surface this via their own readOnly/enabled flag.
  final bool enabled;

  @override
  Widget build(BuildContext context) {
    final field = _field();
    if (errorText == null || currentStrategy() == RenderStrategy.expressive) {
      return field; // expressive renders the error inside _field's decoration
    }
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      mainAxisSize: MainAxisSize.min,
      children: [
        field,
        const SizedBox(height: 6),
        Text(errorText!,
            style: const TextStyle(color: _kFeedbackError, fontSize: 13)),
      ],
    );
  }

  Widget _field() {
    switch (currentStrategy()) {
      case RenderStrategy.glass:
        // The glass IS the surface: a transparent Cupertino field over a real
        // LiquidGlassContainer (not a hard-bordered box).
        return LiquidGlassContainer(
          config: const LiquidGlassConfig(
            effect: LiquidGlassEffect.regular,
            shape: LiquidGlassEffectShape.rect,
          ),
          child: CupertinoTextField(
            controller: controller,
            placeholder: placeholder,
            obscureText: obscure,
            keyboardType: keyboardType,
            enabled: enabled,
            onChanged: onChanged,
            padding: const EdgeInsets.symmetric(horizontal: 18, vertical: 16),
            style: const TextStyle(color: AppTokens.ink, fontSize: 17),
            placeholderStyle: const TextStyle(color: AppTokens.ink3, fontSize: 17),
            decoration: const BoxDecoration(), // transparent — glass shows through
          ),
        );
      case RenderStrategy.expressive:
        return TextField(
          controller: controller,
          obscureText: obscure,
          keyboardType: keyboardType,
          enabled: enabled,
          onChanged: onChanged,
          decoration: InputDecoration(
            hintText: placeholder,
            errorText: errorText,
            filled: true,
            border:
                OutlineInputBorder(borderRadius: BorderRadius.circular(12)),
          ),
        );
      case RenderStrategy.shadcn:
        return ShadInput(
          controller: controller,
          placeholder: placeholder == null ? null : Text(placeholder!),
          obscureText: obscure,
          enabled: enabled,
          onChanged: onChanged,
        );
    }
  }
}

class AdaptiveSegmented extends StatelessWidget {
  const AdaptiveSegmented({
    super.key,
    required this.labels,
    required this.selectedIndex,
    required this.onChanged,
  });
  final List<String> labels;
  final int selectedIndex;
  final ValueChanged<int> onChanged;

  @override
  Widget build(BuildContext context) {
    // Defense-in-depth: every native segmented control backs an ASSERT on
    // non-empty labels (LiquidGlassSegmentedControl line 41: labels.length > 0).
    // The filter labels are an operator-wired stub until they override segLabels;
    // rendering nothing (not asserting) keeps the screen live while the filter is
    // unconfigured. A design with real labels is unaffected (length > 0).
    if (labels.isEmpty) return const SizedBox.shrink();
    switch (currentStrategy()) {
      case RenderStrategy.glass:
        return LiquidGlassSegmentedControl(
          labels: labels,
          selectedIndex: selectedIndex,
          onValueChanged: onChanged,
        );
      case RenderStrategy.expressive:
        // TRUE Compose M3 SingleChoiceSegmentedButtonRow (the signature expressive
        // toggle group), embedded as a platform view with local selection state.
        // A11Y/PARITY: Semantics wrap (see AdaptiveButton) exposes the segment labels
        // to the Android a11y tree (uiautomator/TalkBack) the AndroidView alone hides.
        return Semantics(
          label: labels.join(', '),
          child: _ExpressiveView(
            params: {
              'kind': 'segmented',
              'labels': labels,
              'selectedIndex': selectedIndex,
              'tint': AppTokens.accent.toARGB32(),
            },
            width: null,
            height: 48,
            onMethod: (m, a) {
              if (m == 'onChanged' && a is int) onChanged(a);
            },
          ),
        );
      case RenderStrategy.shadcn:
        // Flutter Material 3 SegmentedButton for web/desktop.
        return SegmentedButton<int>(
          showSelectedIcon: false,
          segments: [
            for (var i = 0; i < labels.length; i++)
              ButtonSegment<int>(value: i, label: Text(labels[i])),
          ],
          selected: {selectedIndex},
          onSelectionChanged: (s) => onChanged(s.first),
          style: SegmentedButton.styleFrom(
            selectedBackgroundColor: AppTokens.accent,
            selectedForegroundColor: AppTokens.paper,
          ),
        );
    }
  }
}

/// A native toggle/switch leaf. DESIGN-AGNOSTIC: glass renders a real UISwitch
