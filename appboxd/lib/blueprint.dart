Uint8List? _rasterizeSvg(String svg, [int size = 54]) {
  final tmpDir = Directory.systemTemp;
  final svgFile =
      File('${tmpDir.path}/bp_${DateTime.now().microsecondsSinceEpoch}.svg');
  final pngFile = File(svgFile.path.replaceAll('.svg', '.png'));
  try {
    svgFile.writeAsStringSync(svg);
    final r = Process.runSync('rsvg-convert',
        ['-w', '$size', '-h', '$size', svgFile.path, '-o', pngFile.path]);
    if (r.exitCode != 0 || !pngFile.existsSync()) {
      stderr.writeln(
          'WARN: rsvg-convert failed: ${r.stderr.toString().trim()}');
      return null;
    }
    return pngFile.readAsBytesSync();
  } catch (e) {
    stderr.writeln('WARN: brand PNG rasterization skipped ($e) — '
        'run `brew install librsvg`, then re-generate');
    return null;
  } finally {
    for (final f in [svgFile, pngFile]) {
      try {
        f.deleteSync();
      } catch (_) {}
    }
  }
}

List<String> _detectedBrands(Map<String, dynamic> breakdown) {
  final found = <String>{};
  void walk(dynamic o) {
    if (o is Map) {
      final pr = o['props'];
      if (pr is Map && _brandRegistry.containsKey(pr['name'])) {
        found.add(pr['name'] as String);
      }
      for (final v in o.values) {
        walk(v);
      }
    } else if (o is List) {
      for (final v in o) {
        walk(v);
      }
    }
  }
  walk(breakdown);
  return found.toList()..sort();
}


List<String> _emitBrandPngs(
    Map<String, dynamic> gen, List<String> detected) {
  final emitted = <String>[];
  for (final name in detected) {
    final entry = _brandRegistry[name];
    if (entry == null || entry.svg == null) continue;
    final png = _rasterizeSvg(entry.svg!);
    if (png == null) break;
    gen['assets/png/brand_$name.png'] = png;
    gen['assets/svg/brand_$name.svg'] = entry.svg!;
    emitted.add(name);
  }
  return emitted;
}

// ──────────────────── JSON ENCODING (sorted keys) ────────────────────

String _sortedJsonEncode(dynamic obj) {
  if (obj is Map) {
    final keys = obj.keys.map((k) => k.toString()).toList()..sort();
    final parts =
        keys.map((k) => '${jsonEncode(k)}: ${_sortedJsonEncode(obj[k])}');
    return '{${parts.join(', ')}}';
  } else if (obj is List) {
    return '[${obj.map(_sortedJsonEncode).join(', ')}]';
  } else {
    return jsonEncode(obj);
  }
}

String _prettySortedJson(dynamic obj, [String indent = '']) {
  if (obj is Map) {
    final keys = obj.keys.map((k) => k.toString()).toList()..sort();
    if (keys.isEmpty) return '{}';
    final next = '$indent  ';
    final parts = keys
        .map((k) => '$next${jsonEncode(k)}: ${_prettySortedJson(obj[k], next)}');
    return '{\n${parts.join(',\n')}\n$indent}';
  } else if (obj is List) {
    if (obj.isEmpty) return '[]';
    final next = '$indent  ';
    final parts = obj.map((e) => '$next${_prettySortedJson(e, next)}');
    return '[\n${parts.join(',\n')}\n$indent]';
  } else {
    return jsonEncode(obj);
  }
}

// ──────────────────── BACKEND CONFIG RESOLVER ────────────────────

List<String> _deriveAuthMethods(Map<String, dynamic>? handlers) {
  final blob = jsonEncode(handlers ?? {});
  final found = <String>{};
  for (final entry in _goTokenMethod.entries) {
    if (blob.contains("go('${entry.key}')") ||
        blob.contains('go("${entry.key}")')) {
      found.add(entry.value);
    }
  }
  return found.toList()..sort();
}

Map<String, dynamic> _backendCfg(
    Map<String, dynamic>? config, Map<String, dynamic>? handlers) {
  final backend = (config?['backend'] as Map?) ?? <String, dynamic>{};
  final derived = _deriveAuthMethods(handlers);
  final cfgMethods = (backend['auth'] as Map?)?['methods'];
  final methodsSet = <String>{...derived};
  if (cfgMethods is List) {
    methodsSet.addAll(cfgMethods.cast<String>());
  }
  final methods = methodsSet.toList()..sort();
  return {
    'provider': backend['provider'] ?? 'supabase',
    'authMethods': methods.isNotEmpty
        ? methods
        : List<String>.from(_backendAuthDefault),
    'offlineMode': (backend['offline'] as Map?)?['mode'] ?? 'off',
    'target': backend['target'] ?? 'local',
  };
}

