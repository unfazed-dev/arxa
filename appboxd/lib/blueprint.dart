    .where((f) => f['serverOnly'] != true)
    .toList();

String _parseExpr(String col, String base, bool nullable) {
  if (base == 'int') {
    return nullable
        ? "(m['$col'] as num?)?.toInt()"
        : "(m['$col'] as num).toInt()";
  }
  if (base == 'double') {
    return nullable
        ? "(m['$col'] as num?)?.toDouble()"
        : "(m['$col'] as num).toDouble()";
  }
  if (base == 'bool') {
    return nullable ? "m['$col'] as bool?" : "m['$col'] as bool";
  }
  if (base == 'DateTime') {
    if (nullable) {
      return "m['$col'] == null ? null : DateTime.parse(m['$col'] as String)";
    }
    return "DateTime.parse(m['$col'] as String)";
  }
  return nullable ? "m['$col'] as String?" : "m['$col'] as String";
}

String _entityDart(Map entity) {
  final cls = _pascal(entity['name'] as String);
  final fields = _entityFields(entity);
  final decls = fields
      .map((f) => '  final ${_dartType(f)} ${_camel(f['name'] as String)};')
      .join('\n');
  final params = fields
      .map((f) =>
          '${_nullable(f) ? '' : 'required '}this.${_camel(f['name'] as String)}')
      .join(', ');
  final fromMap = fields
      .map((f) =>
          '        ${_camel(f['name'] as String)}: ${_parseExpr(f['name'] as String, _dartBase(f), _nullable(f))}')
      .join(',\n');
  return '$genMarker\n'
      '// Domain entity + repository Port from the Domain Model (data_model.json).\n'
      '// Pure Dart (ADR-0003): NO Flutter, NO Supabase. Infrastructure implements it.\n'
      '\n'
      'class $cls {\n'
      '$decls\n'
      '  const $cls({$params});\n'
      '\n'
      '  factory $cls.fromMap(Map<String, dynamic> m) => $cls(\n'
      '$fromMap,\n'
      '      );\n'
      '}\n'
      '\n'
      '/// Repository Port for $cls (RLS scopes rows to the signed-in user).\n'
      'abstract class ${cls}Repository {\n'
      '  Future<List<$cls>> all();\n'
      '}\n';
}

String _supabaseAdapterDart(Map entity) {
  final cls = _pascal(entity['name'] as String);
  final en = _snake(entity['name'] as String);
  final cols = _entityFields(entity).map((f) => f['name'] as String).join(',');
  final order = entity['orderBy'] as String?;
  final orderLine = order != null ? ".order('$order')" : '';
  final clashes = {'Session', 'User'}.contains(cls);
  final hide = clashes ? ' hide $cls' : '';
  final hideNote = clashes
      ? '// `hide $cls` avoids the gotrue symbol clash (Session/User).\n'
      : '// No `hide` — $cls isn\'t a gotrue symbol, so there\'s no clash.\n';
  return '$genMarker\n'
      '// Supabase adapter for $cls (ADR-0003). Supabase CONFINED to infrastructure.\n'
      '$hideNote'
      "import 'package:supabase_flutter/supabase_flutter.dart'$hide;\n"
      '\n'
      "import '../domain/ports/${en}_repository.dart';\n"
      '\n'
      'class ${cls}RepositorySupabase implements ${cls}Repository {\n'
      '  SupabaseClient get _client => Supabase.instance.client;\n'
      '\n'
      '  @override\n'
      '  Future<List<$cls>> all() async {\n'
      "    final rows = await _client.from('${entity['table']}').select('$cols')$orderLine;\n"
      '    return (rows as List)\n'
      '        .map((r) => $cls.fromMap(r as Map<String, dynamic>))\n'
      '        .toList();\n'
      '  }\n'
      '}\n';
}

String _driftColumn(Map f) {
  final name = _camel(f['name'] as String);
  final col = f['name'] as String;
  final method = (_typeMap[f['type']] ?? ['String', 'text', 'text'])[2];
  final getter = _driftGetter[method]!;
  var mods = '';
  if (col != name) mods += ".named('$col')";
  if (_nullable(f)) mods += '.nullable()';
  return '  $getter get $name => $method()$mods();';
}

String _driftDbDart(List entities) {
  final blocks = <String>[];
  for (final e in entities) {
    final em = e as Map;
    final tbl = _pascal(em['table'] as String);
    final cls = _pascal(em['name'] as String);
    final cols = _entityFields(em).map((f) => _driftColumn(f)).join('\n');
    final pk = _entityFields(em)
        .where((f) => f['pk'] == true)
        .map((f) => _camel(f['name'] as String))
        .toList();
    final pkLine = pk.isNotEmpty
        ? '\n  @override\n  Set<Column> get primaryKey => {${pk.join(', ')}};'
        : '';
    blocks.add(
        "@DataClassName('${cls}Row')\nclass $tbl extends Table {\n$cols$pkLine\n}");
  }
  final classes = blocks.join('\n\n');
  final tableList = entities
      .map((e) => _pascal((e as Map)['table'] as String))
      .join(', ');
  return '$genMarker\n'
      '// Local persistence (Drift) — all platforms incl. web (WebAssembly sqlite3).\n'
      '// Tables mirror the domain entities; remote-only owner columns (e.g. user_id)\n'
      '// live solely in Supabase + RLS, never in the local cache.\n'
      "import 'package:drift/drift.dart';\n"
      "import 'package:drift_flutter/drift_flutter.dart';\n"
      '\n'
      "part 'app_database.g.dart';\n"
      '\n'
      '$classes\n'
      '\n'
      '@DriftDatabase(tables: [$tableList])\n'
      'class AppDatabase extends _\$AppDatabase {\n'
      '  AppDatabase._() : super(_open());\n'
      '  static final AppDatabase instance = AppDatabase._();\n'
      '\n'
      '  @override\n'
      '  int get schemaVersion => 1;\n'
      '\n'
      '  @override\n'
      '  MigrationStrategy get migration => MigrationStrategy(\n'
      '        onCreate: (m) => m.createAll(),\n'
      '        onUpgrade: (m, from, to) async {},\n'
      '      );\n'
      '\n'
      '  static QueryExecutor _open() => driftDatabase(\n'
      "        name: 'app_db',\n"
      '        web: DriftWebOptions(\n'
      "          sqlite3Wasm: Uri.parse('sqlite3.wasm'),\n"
      "          driftWorker: Uri.parse('drift_worker.js'),\n"
      '        ),\n'
      '      );\n'
      '}\n';
}

String _localAdapterDart(Map entity) {
  final cls = _pascal(entity['name'] as String);
  final en = _snake(entity['name'] as String);
  final tbl = _pascal(entity['table'] as String);
  final acc = tbl[0].toLowerCase() + tbl.substring(1);
  final fields = _entityFields(entity);
  final row = fields
      .map((f) =>
          '${_camel(f['name'] as String)}: Value(s.${_camel(f['name'] as String)})')
      .join(', ');
  final ent = fields
      .map((f) => '${_camel(f['name'] as String)}: r.${_camel(f['name'] as String)}')
      .join(', ');
  return '$genMarker\n'
      '// Local (Drift) adapter for $cls: offline cache mirroring the entity.\n'
      "import 'package:drift/drift.dart';\n"
      '\n'
      "import '../domain/ports/${en}_repository.dart';\n"
      "import 'local/app_database.dart' hide $tbl;\n"
      '\n'
      'class ${cls}RepositoryLocal implements ${cls}Repository {\n'
      '  AppDatabase get _db => AppDatabase.instance;\n'
      '\n'
      '  ${tbl}Companion _row($cls s) => ${tbl}Companion($row);\n'
      '\n'
      '  Future<void> upsertAll(List<$cls> items) =>\n'
      '      _db.batch((b) => b.insertAllOnConflictUpdate(\n'
      '          _db.$acc, [for (final s in items) _row(s)]));\n'
      '\n'
      '  @override\n'
      '  Future<List<$cls>> all() async {\n'
      '    final rows = await _db.select(_db.$acc).get();\n'
      '    return [for (final r in rows) $cls($ent)];\n'
      '  }\n'
      '}\n';
}

String _cachedAdapterDart(Map entity) {
  final cls = _pascal(entity['name'] as String);
  final en = _snake(entity['name'] as String);
  return '$genMarker\n'
      '// Read-through cache for $cls: remote (Supabase) refreshes the local (Drift)\n'
      '// store on every read; offline → serve the cached rows.\n'
      "import '../domain/ports/${en}_repository.dart';\n"
      "import '${en}_repository_supabase.dart';\n"
      "import '${en}_repository_local.dart';\n"
      '\n'
      'class ${cls}RepositoryCached implements ${cls}Repository {\n'
      '  final _remote = ${cls}RepositorySupabase();\n'
      '  final _local = ${cls}RepositoryLocal();\n'
      '\n'
      '  @override\n'
      '  Future<List<$cls>> all() async {\n'
      '    try {\n'
      '      final rows = await _remote.all();\n'
      '      try {\n'
      '        await _local.upsertAll(rows);\n'
      '      } catch (_) {}\n'
      '      return rows;\n'
      '    } catch (_) {\n'
      '      try {\n'
      '        return await _local.all();\n'
      '      } catch (_) {\n'
      '        return const <$cls>[];\n'
      '      }\n'
      '    }\n'
      '  }\n'
      '}\n';
}

String _sqlColumn(Map f) {
  final sqlt = (_typeMap[f['type']] ?? <dynamic>[null, 'text', null])[1] as String;
  var s = "${f['name']} $sqlt";
  if (f['pk'] == true) s += ' primary key';
  if (f['default'] != null) s += ' default ${f['default']}';
  if (f['references'] != null) {
    s += ' references ${f['references']}(id) on delete cascade';
  }
  if (f['notNull'] == true && f['pk'] != true) s += ' not null';
  return s;
}

String _migrationSql(List entities) {
  final out = <String>[
    '-- AUTO-GENERATED by flutter_crew from data_model.json — schema + RLS.',
    '-- Apply via the Supabase MCP: apply_migration(name, <this file>).',
    'create extension if not exists pgcrypto;',
    '',
  ];
  for (final e in entities) {
    final em = e as Map;
    final t = em['table'] as String;
    final cols = (em['fields'] as List)
        .map((f) => '  ${_sqlColumn(f as Map)}')
        .join(',\n');
    out.add('create table if not exists public.$t (\n$cols\n);');
    out.add('alter table public.$t enable row level security;');
    final ownerField = (em['fields'] as List).cast<Map?>().firstWhere(
        (f) => f?['owner'] == true, orElse: () => null);
    final owner = ownerField?['name'];
    if (owner != null) {
      out.add('drop policy if exists "${t}_rw_own" on public.$t;');
      out.add('create policy "${t}_rw_own" on public.$t\n'
          '  for all to authenticated\n'
          '  using ((select auth.uid()) = $owner)\n'
          '  with check ((select auth.uid()) = $owner);');
    } else {
      out.add('drop policy if exists "${t}_read_auth" on public.$t;');
      out.add('create policy "${t}_read_auth" on public.$t '
          'for select to authenticated using (true);');
    }
    out.add('');
  }
  return '${out.join('\n')}\n';
}

String _sqlVal(dynamic v) {
  if (v == null) return 'null';
  if (v is bool) return v ? 'true' : 'false';
  if (v is int || v is double) return v.toString();
  return "'${v.toString().replaceAll("'", "''")}'";
}

