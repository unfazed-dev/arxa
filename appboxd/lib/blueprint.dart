String _seedUuid(int i) =>
    '5e551000-0000-4000-8000-${(i + 1).toString().padLeft(12, '0')}';

String _dateFromLast(dynamic last, String? anchor) {
  if (anchor == null) return '';
  final parts = anchor.split('-');
  if (parts.length != 3) return anchor;
  final base =
      DateTime(int.parse(parts[0]), int.parse(parts[1]), int.parse(parts[2]));
  final s = (last ?? '').toString().trim().toLowerCase();
  var days = 0;
  if (s == 'yesterday') {
    days = 1;
  } else {
    final m = RegExp(r'(\d+)\s*([dw])').firstMatch(s);
    if (m != null) {
      days = int.parse(m.group(1)!) * (m.group(2) == 'w' ? 7 : 1);
    }
  }
  final result = base.subtract(Duration(days: days));
  return '${result.year.toString().padLeft(4, '0')}-'
      '${result.month.toString().padLeft(2, '0')}-'
      '${result.day.toString().padLeft(2, '0')}';
}

List _designSeed(String? dataModelPath, String source) {
  if (dataModelPath == null || dataModelPath.isEmpty) return [];
  final djsx =
      p.join(p.dirname(p.absolute(dataModelPath)), 'design', 'data.jsx');
  if (!File(djsx).existsSync()) return [];
  // capture_data.extract_data_model is a sibling Python stage not ported to
  // Dart; degrade to no design seed (matches Python's except branch).
  return [];
}

List<Map<String, dynamic>> _projectSeedRows(
    Map entity, List designSeed, Map? authUser) {
  final spec = entity['seedFrom'] as Map?;
  if (spec == null) {
    return ((entity['seed'] as List?) ?? [])
        .cast<Map<String, dynamic>>()
        .toList();
  }
  final colmap = (spec['map'] as Map?) ?? {};
  final datecfg = (spec['date'] as Map?) ?? {};
  final fields = entity['fields'] as List;
  final ownerField =
      fields.cast<Map?>().firstWhere((f) => f?['owner'] == true, orElse: () => null);
  final owner = ownerField?['name'];
  final rows = <Map<String, dynamic>>[];
  for (var i = 0; i < designSeed.length; i++) {
    final dr = designSeed[i] as Map;
    final row = <String, dynamic>{};
    for (final f in fields.cast<Map>()) {
      final n = f['name'] as String;
      if (f['pk'] == true && f['type'] == 'uuid' && f['references'] == null) {
        row[n] = _seedUuid(i);
      } else if (n == owner && authUser != null) {
        row[n] = authUser['id'];
      } else if (colmap.containsKey(n) && dr.containsKey(colmap[n])) {
        row[n] = dr[colmap[n]];
      } else if (n == datecfg['column']) {
        row[n] = _dateFromLast(dr[datecfg['from']], datecfg['anchor'] as String?);
      }
    }
    rows.add(row);
  }
  return rows;
}

String _seedSql(List entities, Map? authUser,
    [String? dataModelPath]) {
  final out = <String>[
    '-- AUTO-GENERATED seed — re-runnable: design-sourced rows are DELETE-then-',
    '-- inserted per auth user (so re-seeding reflects the current design); fixed uuids.',
    '-- Seed VALUES come from the design itself (design/data.jsx), projected onto the',
    '-- schema; the Domain Model declares only structure. Apply: execute_sql(<this file>).',
    '',
  ];
  if (authUser != null) {
    out.add(_authUserSql(authUser['id'] as String, authUser['email'] as String,
        authUser['password'] as String));
  }
  final designEntity = entities.cast<Map?>().firstWhere(
      (e) => (e?['seedFrom'] as Map?)?['source'] != null,
      orElse: () => null);
  final designSource = (designEntity?['seedFrom'] as Map?)?['source'] as String?;
  final designSeed =
      designSource != null ? _designSeed(dataModelPath, designSource) : [];
  for (final e in entities) {
    final em = e as Map;
    final rows = _projectSeedRows(em, designSeed, authUser);
    if (rows.isEmpty) continue;
    final cols = rows.first.keys.toList();
    final values = rows
        .map((r) => '(${cols.map((c) => _sqlVal(r[c])).join(', ')})')
        .join(',\n  ');
    if (em['seedFrom'] != null &&
        authUser != null &&
        cols.contains('user_id')) {
      out.add(
          'delete from public.${em['table']} where user_id = ${_sqlVal(authUser['id'])};');
    }
    out.add('insert into public.${em['table']} (${cols.join(', ')}) values\n  $values\n'
        'on conflict do nothing;');
    out.add('');
  }
  return '${out.join('\n')}\n';
}

Map<String, dynamic> _loadDataModel(String? path) {
  if (path == null || path.isEmpty || !File(path).existsSync()) return {};
  final doc =
      jsonDecode(File(path).readAsStringSync()) as Map<String, dynamic>;
  if (doc['data_model'] is Map) {
    return doc['data_model'] as Map<String, dynamic>;
  }
  return doc;
}

