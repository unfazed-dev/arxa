/// Hosts a TRUE Android Material 3 Expressive primitive (Jetpack Compose) via a
/// Flutter PlatformView. Leaf widgets only — see the file header. The Kotlin side
/// (ExpressivePlatformView.kt, emitted by emit.py) renders `params['kind']`
/// and calls back over MethodChannel 'appbox/expressive/$id'. Only ever built on
/// Android (the expressive strategy is Android-only), but compiles everywhere.
class _ExpressiveView extends StatefulWidget {
  const _ExpressiveView({
    required this.params,
    required this.width, // null → expand to the parent's width
    required this.height,
    this.onMethod,
    this.wrap = false, // content-width: start at `width` (estimate), shrink to measured
  });
  final Map<String, dynamic> params;
  final double? width;
  final double height;
  final void Function(String method, dynamic args)? onMethod;
  final bool wrap;

  @override
  State<_ExpressiveView> createState() => _ExpressiveViewState();
}

class _ExpressiveViewState extends State<_ExpressiveView> {
  MethodChannel? _channel;
  double? _measuredW; // native content width (dp) reported via the size round-trip

  @override
  void didUpdateWidget(covariant _ExpressiveView oldWidget) {
    super.didUpdateWidget(oldWidget);
    // creationParams are immutable post-creation — an AndroidView sends them ONCE. So when
    // the Dart side rebuilds with new params (e.g. the Send-code button's `enabled` flips
    // false→true as the email becomes valid, or tint changes), the Kotlin side would NEVER
    // see the update and the button renders frozen at its creation-time state (proven via
    // appbox lens: the Dart `enabled` flips correctly but the rendered colour never changes).
    // Push the volatile fields (enabled/tint/fg/busy/label/trailing) over the existing
    // MethodChannel so the Compose side can recompose with the new values.
    final ch = _channel;
    if (ch == null) return;
    final np = widget.params, op = oldWidget.params;
    final delta = <String, dynamic>{};
    for (final k in const ['enabled', 'tint', 'fg', 'busy', 'label', 'trailing']) {
      if (np[k] != op[k]) delta[k] = np[k];
    }
    if (delta.isNotEmpty) {
      ch.invokeMethod('update', delta);
    }
  }

  @override
  void dispose() {
    _channel?.setMethodCallHandler(null);
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    // wrap → use the estimate until the native view reports its content width,
    // then tighten. Non-wrap → fixed width (or infinity = fill parent).
    final w = widget.wrap ? (_measuredW ?? widget.width) : widget.width;
    return SizedBox(
      width: w ?? double.infinity,
      height: widget.height,
      child: AndroidView(
        viewType: 'appbox/expressive',
        creationParams: widget.params,
        creationParamsCodec: const StandardMessageCodec(),
        // Claim touches eagerly so the embedded Compose view receives taps even
        // inside a scrollable (a plain AndroidView loses the gesture arena to the
        // parent ListView — taps never reach the segmented control otherwise).
        gestureRecognizers: const <Factory<OneSequenceGestureRecognizer>>{
          Factory<OneSequenceGestureRecognizer>(EagerGestureRecognizer.new),
        },
        onPlatformViewCreated: (id) {
          _channel = MethodChannel('appbox/expressive/$id')
            ..setMethodCallHandler((call) async {
              if (call.method == 'onMeasured') {
                final a = call.arguments;
                final nw = (a is List && a.isNotEmpty && a[0] is num)
                    ? (a[0] as num).toDouble()
                    : null;
                // Only rebuild on a real change → avoids a measure↔layout loop.
                if (nw != null &&
                    nw > 0 &&
                    (_measuredW == null || (nw - _measuredW!).abs() > 0.5)) {
                  setState(() => _measuredW = nw);
                }
                return null;
              }
              widget.onMethod?.call(call.method, call.arguments);
              return null;
            });
        },
      ),
    );
  }
}

