/// A selectable chip/filter-pill leaf. The design's tap-only selectable pills
/// (filter-chip, label-pill, mini-seg-opt, seg-opt, fb-tag, tempo-chip, fb-emoji,
/// avatar-color-dot). DESIGN-AGNOSTIC: glass renders a LiquidGlassContainer
/// surface + a Flutter label (no native chip in the glass toolkit — the hybrid
/// surface policy, same as AdaptiveTextField), expressive a Compose `FilterChip`
/// via _ExpressiveView(kind:'chip'), shadcn a ShadButton-as-toggle. Selection is
/// carried in `selected`; the tap is reported via onTap (a VoidCallback, not a
/// value — the owning list/segment decides what selection means).
class AdaptiveChip extends StatelessWidget {
  const AdaptiveChip({
    super.key,
    required this.label,
    required this.onTap,
    this.selected = false,
    this.tint,
  });
  final String label;
  final VoidCallback onTap;
  final bool selected;
  final Color? tint;

  @override
  Widget build(BuildContext context) {
    final accent = tint ?? AppTokens.accent;
    switch (currentStrategy()) {
      case RenderStrategy.glass:
        // Hybrid surface: a real LiquidGlassContainer (native glass) wrapping a
