String _htmlUnescape(String s) => s
    .replaceAll('&amp;', '&')
    .replaceAll('&lt;', '<')
    .replaceAll('&gt;', '>')
    .replaceAll('&quot;', '"')
    .replaceAll('&#39;', "'")
    .replaceAll('&apos;', "'")
    .replaceAll('&nbsp;', ' ');

String _titleCase(String s) {
  final buf = StringBuffer();
  var prevIsLetter = false;
  for (final c in s.split('')) {
    final isLetter = RegExp(r'[a-zA-Z]').hasMatch(c);
    if (isLetter && !prevIsLetter) {
      buf.write(c.toUpperCase());
    } else if (isLetter) {
      buf.write(c.toLowerCase());
    } else {
      buf.write(c);
    }
    prevIsLetter = isLetter;
  }
  return buf.toString();
}

String _designTitle(String source) {
  try {
    final text = File(source).readAsStringSync();
    final m = RegExp(r'<title[^>]*>(.*?)</title>',
            caseSensitive: false, dotAll: true)
        .firstMatch(text);
    if (m == null) return '';
    return _htmlUnescape(m.group(1)!).trim();
  } catch (_) {
    return '';
  }
}

String _brandSegment(String raw) {
  final m = RegExp(r'\s+[—:\-|·;]\s+').firstMatch(raw);
  if (m == null) return raw.trim();
  final seg = raw.substring(0, m.start).trim();
  return seg.isNotEmpty ? seg : raw.trim();
}

String _appDisplayName(String source, [String? override]) {
  if (override != null && override.trim().isNotEmpty) {
    return override.trim();
  }
  final title = _designTitle(source);
  final seg = title.isNotEmpty ? _brandSegment(title) : '';
  if (seg.isNotEmpty) return seg;
  final base = p
      .basename(source.isEmpty ? 'App' : source)
      .replaceAll(RegExp(r'\.(html|jsx|tsx)$', caseSensitive: false), '');
  final result = _titleCase(base.trim());
  return result.isEmpty ? 'Crew App' : result;
}

String _appName(String source, [String? override]) {
  String raw;
  if (override != null && override.trim().isNotEmpty) {
    raw = override.trim();
  } else {
    final title = _designTitle(source);
    if (title.isNotEmpty) {
      raw = _brandSegment(title);
    } else {
      raw = p
          .basename(source.isEmpty ? 'app' : source)
          .replaceAll(RegExp(r'\.(html|jsx|tsx)$', caseSensitive: false), '');
    }
  }
  final result = raw
      .replaceAll(RegExp(r'[^0-9a-zA-Z]+'), '_')
      .replaceAll(RegExp(r'^_+|_+$'), '')
      .toLowerCase();
  return result.isEmpty ? 'crew_app' : result;
}

