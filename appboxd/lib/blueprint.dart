/// Rise-in entrance — the design's staggered `.rise` cascade: each element holds
/// faded/+`dy`px for its own `delayMs`, then runs the captured `curve` over
/// `durationMs`. CONTROLLER-driven and started from a POST-FRAME callback, NOT at
/// build time. Why: the sign-in view is pushed after a ~2s splash; a build-time
/// implicit `TweenAnimationBuilder` played (and finished) while the view was still
/// off-screen behind the splash, so on device the cascade never showed (measured:
/// a 0.27s pop-in then dead-static, vs the design's ~1s cascade). Starting on the
/// first mounted frame makes every element begin from the same on-screen moment;
/// the per-element `delayMs` Interval IS the stagger. A controller (vs implicit
/// tween) also survives view-model rebuilds without restarting.
///
/// Glass note: wrapping an iOS Liquid Glass platform view in Opacity/Transform
/// breaks native compositing, so native-control wrappers pass skipOnGlass:true and
/// render directly under glass — iOS will NOT animate those button rows (a native
/// platform-view limit, not a bug). Flutter-drawn nodes (logo/text/footer) pass
/// skipOnGlass:false and animate on every platform. durationMs/curve/dy are the
/// captured design tokens (kRiseMs/kRiseCurve/kRiseDy); delayMs is the per-element
/// captured animation-delay.
class GlassEntrance {
  /// A native iOS Liquid Glass entrance descriptor (ADR: glass_entrance.py). The
  /// design's time-based bezier tween MAPPED onto a native glass spring — never a
  /// Flutter fade over a UiKitView (flutter#93757). Cooked once per view from the
  /// captured rise tokens (glass_entrance.design_to_glass); each glass leaf receives
  /// its own `delayMs` (the cross-element stagger) so the native entrance lands in
  /// step with the text cascade. The native mount hook that flips `appeared` after
  /// delayMs is the one piece not yet in native_liquid_glass (a small native add
  /// mirroring setPressed); until then this is a STABLE DATA HOLDER the primitives
  /// accept, so views compile + the descriptor is forward-compatible. Fields mirror
  /// design_to_glass() exactly: {delayMs, response_s, bounce, opacityFrom, scaleFrom,
  /// liftPx, materialize, preset}.
  const GlassEntrance({
    this.delayMs = 0,
    this.responseS = 0.5,
    this.bounce = 0.0,
    this.opacityFrom = 0.0,
    this.scaleFrom = 0.92,
    this.liftPx = 14,
    this.materialize = true,
    this.preset = 'smooth',
  });
  final int delayMs;           // stagger preserved (the cross-element delay)
  final double responseS;      // spring duration (durMs/1000)
  final double bounce;         // bezier overshoot -> spring bounce
  final double opacityFrom;    // native hide channel (UIView.alpha 0<->1)
  final double scaleFrom;      // gentle grow-in accent (~0.92, NOT the hide channel)
  final double liftPx;         // the rise (native .offset), kept from the design dy
  final bool materialize;      // Apple .glassEffectTransition(.materialize) polish
  final String preset;         // nearest LiquidGlassSpring preset (smooth/snappy/…)
}

class RiseIn extends StatefulWidget {
  const RiseIn(
      {super.key,
      required this.child,
      this.delayMs = 0,
      this.durationMs = 550,
      this.curve = Curves.easeOutCubic,
      this.dy = 14,
      this.skipOnGlass = true});
  final Widget child;
  final int delayMs;
