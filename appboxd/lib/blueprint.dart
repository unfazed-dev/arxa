String _authMethodDart(List<String>? methods) {
  final m = (methods ?? const <String>[]).toSet();
  final out = <String>[];
  if (m.contains('emailOtp')) {
    out.add("  /// Email OTP (ADR-0003): emails a one-time code to [email] (no deep link).\n"
        '  Future<void> sendEmailOtp({required String email}) =>\n'
        '      Supabase.instance.client.auth.signInWithOtp(email: email);\n'
        '\n'
        '  /// Verifies the emailed OTP [token]; on success a session is established.\n'
        '  Future<AuthResponse> verifyEmailOtp(\n'
        '          {required String email, required String token}) =>\n'
        '      Supabase.instance.client.auth\n'
        '          .verifyOTP(email: email, token: token, type: OtpType.email);');
  }
  if (m.contains('magicLink')) {
    out.add("  /// Magic link (ADR-0003): emails a sign-in link; completion arrives via the\n"
        '  /// deep link in capabilityConfig.deepLinks.scheme.\n'
        '  Future<void> sendMagicLink({required String email, String? redirectTo}) =>\n'
        '      Supabase.instance.client.auth\n'
        '          .signInWithOtp(email: email, emailRedirectTo: redirectTo);');
  }
  if (m.contains('googleOAuth')) {
    out.add("  /// Native Google sign-in (google_sign_in v7): gets an idToken from Google, then\n"
        '  /// exchanges it with Supabase (signInWithIdToken). Client IDs are supplied\n'
        '  /// out-of-band via --dart-define. See docs/plans/operator-auth-setup.md.\n'
        '  Future<AuthResponse> signInWithGoogle() async {\n'
        "    const webClientId = String.fromEnvironment('GOOGLE_SERVER_CLIENT_ID');\n"
        "    const iosClientId = String.fromEnvironment('GOOGLE_IOS_CLIENT_ID');\n"
        '    if (webClientId.isEmpty) {\n'
        '      throw const AuthException(\n'
        "          'Google sign-in not configured. Pass '\n"
        "          '--dart-define=GOOGLE_SERVER_CLIENT_ID=<web client id> '\n"
        "          '(and GOOGLE_IOS_CLIENT_ID on iOS). See docs/plans/operator-auth-setup.md.');\n"
        '    }\n'
        '    final google = GoogleSignIn.instance;\n'
        '    await google.initialize(\n'
        '        serverClientId: webClientId,\n'
        '        clientId: iosClientId.isEmpty ? null : iosClientId);\n'
        '    final account = await google.authenticate();\n'
        '    final idToken = account.authentication.idToken;\n'
        '    if (idToken == null) {\n'
        "      throw const AuthException('Google sign-in returned no idToken.');\n"
        '    }\n'
        '    const scopes = ['
        "'email', 'profile'"
        '];\n'
        '    final authz =\n'
        '        await account.authorizationClient.authorizationForScopes(scopes) ??\n'
        '            await account.authorizationClient.authorizeScopes(scopes);\n'
        '    return Supabase.instance.client.auth.signInWithIdToken(\n'
        '      provider: OAuthProvider.google,\n'
        '      idToken: idToken,\n'
        '      accessToken: authz.accessToken,\n'
        '    );\n'
        '  }');
  }
  if (m.contains('appleOAuth')) {
    out.add("  /// Native Apple sign-in (sign_in_with_apple ^8.1.0): the nonce contract is\n"
        '  /// sha256(raw) → Apple, raw → Supabase. iOS uses the native sheet.\n'
        '  /// See docs/plans/operator-auth-setup.md.\n'
        '  Future<AuthResponse> signInWithApple() async {\n'
        '    final rawNonce = Supabase.instance.client.auth.generateRawNonce();\n'
        '    final hashedNonce = sha256.convert(utf8.encode(rawNonce)).toString();\n'
        "    const serviceId = String.fromEnvironment('APPLE_SERVICE_ID');\n"
        "    const redirect = String.fromEnvironment('APPLE_REDIRECT_URI');\n"
        '    final credential = await SignInWithApple.getAppleIDCredential(\n'
        '      scopes: const [\n'
        '        AppleIDAuthorizationScopes.email,\n'
        '        AppleIDAuthorizationScopes.fullName,\n'
        '      ],\n'
        '      nonce: hashedNonce,\n'
        '      webAuthenticationOptions: serviceId.isEmpty\n'
        '          ? null\n'
        '          : WebAuthenticationOptions(\n'
        '              clientId: serviceId, redirectUri: Uri.parse(redirect)),\n'
        '    );\n'
        '    final idToken = credential.identityToken;\n'
        '    if (idToken == null) {\n'
        "      throw const AuthException('Apple sign-in returned no identityToken.');\n"
        '    }\n'
        '    return Supabase.instance.client.auth.signInWithIdToken(\n'
        '      provider: OAuthProvider.apple,\n'
        '      idToken: idToken,\n'
        '      nonce: rawNonce,\n'
        '    );\n'
        '  }');
  }
  return out.join('\n');
}

