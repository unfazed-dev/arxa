String _pascal(String s) {
  final parts = s
      .split(RegExp(r'[^0-9a-zA-Z]+'))
      .where((p) => p.isNotEmpty)
      .toList();
  if (parts.isEmpty) return 'Screen';
  parts[0] = parts[0].replaceAll(RegExp(r'^[^a-zA-Z]+'), '');
  if (parts[0].isEmpty) parts[0] = 'S';
  return parts.map((p) => p[0].toUpperCase() + p.substring(1)).join();
}

String _snake(String s) {
  s = s.replaceAllMapped(
      RegExp(r'(.)([A-Z][a-z]+)'), (m) => '${m[1]}_${m[2]}');
  s = s.replaceAllMapped(
      RegExp(r'([a-z0-9])([A-Z])'), (m) => '${m[1]}_${m[2]}');
  s = s.replaceAll(RegExp(r'[^0-9a-zA-Z]+'), '_');
  final stripped = s
      .replaceAll(RegExp(r'^_+'), '')
      .replaceAll(RegExp(r'_+$'), '')
      .toLowerCase();
  return stripped.isEmpty ? 'screen' : stripped;
}

String _camel(String s) {
  final parts = s
      .split(RegExp(r'[^0-9a-zA-Z]+'))
      .where((p) => p.isNotEmpty)
      .toList();
  if (parts.isEmpty) return 'field';
  return parts[0].toLowerCase() +
      parts.skip(1).map((p) => p[0].toUpperCase() + p.substring(1)).join();
}

String _dartStr(String s) =>
