String? _loadTokensDart(String? tokensPath) {
  if (tokensPath == null || !File(tokensPath).existsSync()) return null;
  try {
    final tree =
        jsonDecode(File(tokensPath).readAsStringSync()) as Map<String, dynamic>;
    return emitDart(tree);
  } catch (e) {
    stderr.writeln('blueprint: tokens transform skipped ($e)');
    return null;
  }
}

