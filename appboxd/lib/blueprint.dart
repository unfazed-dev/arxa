Map<String, dynamic> _assemble({
  required Map<String, dynamic> breakdown,
  required String outDir,
  String? tokensPath,
  String factoryV = factoryVersion,
  String generated = '2026-06-20T00:00:00Z',
  String stack = 'stacked',
  String? appNameOverride,
  String? dataModelPath,
  Map<String, dynamic>? backend,
}) {
  final meta = (breakdown['meta'] as Map?) ?? {};
  final source = (meta['source'] as String?) ?? 'app';
  final appName = _appName(source, appNameOverride);
  final displayName = _appDisplayName(source, appNameOverride);
  final platforms =
      (meta['platforms'] as List?)?.cast<String>() ?? ['ios', 'android', 'web'];
  final screens = (breakdown['screenFlow'] as List?)?.cast<Map>() ?? [];
  final primaryNav = breakdown['primaryNav'] as Map<String, dynamic>?;
  final dataModel = _loadDataModel(dataModelPath);
  final entities = (dataModel['entities'] as List?)?.cast<Map>() ?? [];

  Directory(outDir).createSync(recursive: true);
  final tdir = p.join(outDir, 'templates');
  final lib = p.join(tdir, 'lib');
  for (final d in [
    p.join(lib, 'app'),
    p.join(lib, 'ui'),
    p.join(lib, 'domain', 'ports'),
    p.join(lib, 'application'),
    p.join(lib, 'infrastructure'),
    p.join(lib, 'presentation'),
    p.join(tdir, 'test'),
  ]) {
    Directory(d).createSync(recursive: true);
  }

  final authMethods = backend?['authMethods'] as List<String>? ??
      List<String>.from(_backendAuthDefault);

  // --- generated layer ---
  final gen = <String, dynamic>{
    'lib/main.dart': _tplMain(displayName),
    'lib/app/app.dart':
        _tplApp(appName, screens, platforms, entities, primaryNav),
    'lib/ui/render_strategy.dart': _tplRenderStrategy(),
    'lib/ui/primitives.dart': _tplPrimitives(
      _brandRegistry.entries
          .where((e) => e.value.colorMode == 'mono')
          .map((e) => e.key)
          .toList()
        ..sort(),
      {
        for (final e in _brandRegistry.entries)
          if (e.value.platforms != null) e.key: e.value.platforms!,
      },
    ),
    'lib/ui/feedback_service.dart': _tplFeedbackService(),
    'lib/ui/app_theme.dart': _tplTheme(),
    'lib/domain/ports/repository.dart': _tplPorts(),
    'lib/infrastructure/supabase_client.dart': _tplSupabaseClient(),
    'lib/infrastructure/supabase_auth_service.dart':
        _tplSupabaseAuth(authMethods),
    'lib/infrastructure/base_supabase_repository.dart': _tplBaseRepo(),
    'pubspec.yaml': _tplPubspec(appName, source, authMethods),
    'analysis_options.yaml': _tplAnalysisOptions(),
  };

  // root nav shell
  if (primaryNav != null &&
      primaryNav['tabs'] is List &&
      (primaryNav['tabs'] as List).isNotEmpty) {
    final tabIds = (primaryNav['tabs'] as List)
        .map((t) => (t as Map)['id'] as String)
        .toSet();
    final tabScreens =
        screens.where((s) => tabIds.contains(s['id'])).toList();
    if (tabScreens.isNotEmpty) {
      gen['lib/presentation/home_shell_view.dart'] =
          _tplNavShellView(tabScreens, primaryNav);
      gen['lib/presentation/root_navigation_viewmodel.dart'] =
          _tplNavShellVm(tabScreens, primaryNav);
    }
  }

  // token layer
  final tokensDart = _loadTokensDart(tokensPath);
  gen['lib/app_tokens.dart'] = tokensDart ?? _tokensStub();

  // domain model projections
  for (final e in entities) {
    final en = _snake(e['name'] as String);
    gen['lib/domain/ports/${en}_repository.dart'] = _entityDart(e);
    gen['lib/infrastructure/${en}_repository_supabase.dart'] =
        _supabaseAdapterDart(e);
    gen['lib/infrastructure/${en}_repository_local.dart'] =
        _localAdapterDart(e);
    gen['lib/infrastructure/${en}_repository_cached.dart'] =
        _cachedAdapterDart(e);
  }
  if (entities.isNotEmpty) {
    gen['lib/infrastructure/local/app_database.dart'] = _driftDbDart(entities);
    gen['supabase/migrations/0001_init.sql'] = _migrationSql(entities);
    gen['supabase/seed.sql'] =
        _seedSql(entities, dataModel['authUser'] as Map?, dataModelPath);
  }

  // extension points
  final ext = <String, dynamic>{};
  for (final s in screens) {
    final snakeId = _snake(s['id'] as String);
    ext['lib/presentation/${snakeId}_view.dart'] = _tplView(s);
    ext['lib/presentation/${snakeId}_viewmodel.dart'] = _tplViewModel(s);
  }

  // brand sign-in glyphs
  final detected = _detectedBrands(breakdown);
  _emitBrandPngs(gen, detected);

  // write all files
  for (final entry in {...gen, ...ext}.entries) {
    final rel = entry.key;
    final content = entry.value;
    final path = p.join(tdir, rel);
    Directory(p.dirname(path)).createSync(recursive: true);
    if (content is Uint8List) {
      File(path).writeAsBytesSync(content);
    } else {
      File(path).writeAsStringSync(content as String);
    }
  }

  // tokens tree for golden + manifest
  Map<String, dynamic> tokensTree = {};
  if (tokensPath != null && File(tokensPath).existsSync()) {
    try {
      tokensTree = jsonDecode(File(tokensPath).readAsStringSync())
          as Map<String, dynamic>;
    } catch (_) {
      tokensTree = {};
    }
  }

  final golden = _golden(breakdown, tokensTree, dataModel);

  final manifest = <String, dynamic>{
    'factoryVersion': factoryV,
    'source': source,
    'stack': stack,
    'lastMode': 'new-app',
    'blueprintHash': golden,
    'templatesVersion': templatesVersion,
    'generated': generated,
    'platforms': platforms,
    'crewVersion': meta['crewVersion'],
    'appName': appName,
    'displayName': displayName,
    'generatedLayer': gen.keys.toList()..sort(),
    'extensionPoints': ext.keys.toList()..sort(),
    'screens': screens
        .map((s) => {
              'id': s['id'],
              'class': _pascal(s['id'] as String),
              'route': _snake(s['id'] as String),
              'status': (s['status'] as String?) ?? 'full',
            })
        .toList(),
  };

  File(p.join(outDir, 'manifest.json'))
      .writeAsStringSync('${_prettySortedJson(manifest)}\n');
  File(p.join(outDir, 'golden.sha256')).writeAsStringSync('$golden\n');
  File(p.join(outDir, 'playbook.md'))
      .writeAsStringSync(_playbook(appName, screens, platforms, golden));

  return {
    'manifest': manifest,
    'generated': gen.length,
    'extension': ext.length,
    'golden': golden,
    'app': appName,
    'display': displayName,
  };
}

// ──────────────────── ENTRY POINT ────────────────────

int buildBlueprint(String breakdownPath, String outDir, {String? tokensPath}) {
  try {
    final breakdown = jsonDecode(File(breakdownPath).readAsStringSync())
        as Map<String, dynamic>;

    // Look for co-located handlers.json (same dir as breakdown)
    final handlersPath =
        p.join(p.dirname(p.absolute(breakdownPath)), 'handlers.json');
    Map<String, dynamic> handlers = {};
    if (File(handlersPath).existsSync()) {
      handlers = jsonDecode(File(handlersPath).readAsStringSync())
          as Map<String, dynamic>;
    }
    final backend = _backendCfg(null, handlers);

    final r = _assemble(
      breakdown: breakdown,
      outDir: outDir,
      tokensPath: tokensPath,
      backend: backend,
    );
    final m = r['manifest'] as Map<String, dynamic>;
    stdout.writeln('blueprint → $outDir');
    stdout.writeln(
        '  app=${r['app']} display=${r['display']} golden=${(r['golden'] as String).substring(0, 12)}…');
    stdout.writeln(
        '  generated-layer=${r['generated']} extension-points=${r['extension']} '
        'screens=${(m['screens'] as List).length} platforms=${(m['platforms'] as List).join(',')}');
    stdout.writeln('  manifest + golden.sha256 + playbook.md written');
    return 0;
  } catch (e, st) {
    stderr.writeln('blueprint failed: $e');
    stderr.writeln(st);
    return 1;
  }
}